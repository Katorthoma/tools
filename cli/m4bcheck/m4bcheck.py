def stage_repair(
    plan: RepairPlan,
    tempdir: Path,
    *,
    atomicparsley: str | None,
    progress: ProgressReporter | None = None,
) -> tuple[Path, Path | None, Path | None, list[str]]:
    warnings: list[str] = []
    audio_only = tempdir / "audio.m4b"
    cover_file = tempdir / "cover.jpg"
    metadata_sidecar: Path | None = None
    cover_sidecar: Path | None = None
    _ = atomicparsley  # retained for CLI/backward compatibility; standard mode no longer needs it

    if plan.tag_mode == "standard":
        # Do not feed the source cover stream to ffmpeg.  The real Audible cover
        # advertises book-long timing and pathological packet timestamps, which
        # can wedge a naive -c:v copy.  Encode/remux audio + chapters first, then
        # transplant the source MP4 user-data capsule.  covr artwork therefore
        # survives byte-for-byte without ever becoming a timed ffmpeg input.
        encode_or_remux(plan, audio_only)
        if progress is not None:
            action_word = "Remux" if plan.action == RepairAction.REMUX else "Encode"
            progress.stage(f"{action_word} complete; preserving exact MP4 user metadata...")
        capsule = transplant_user_data(plan.source, audio_only, keep_cover=plan.keep_cover)
        if progress is not None:
            progress.stage("metadata transplant complete; preparing verification gate...")
        warnings.append(
            f"metadata preserved as exact MP4 user-data capsule ({capsule.ilst_atom_count} ilst atom(s))"
        )
        # A failed structured probe is distinct from an empty/negative result.
        # Abort here before the more expensive verification pass if the splice
        # made the container unreadable for any reason.
        probe_file(audio_only)
        return audio_only, None, None, warnings

    # QT mode keeps all metadata in ffmpeg's QuickTime keys/ilst representation.
    # The ffmpeg muxer cannot combine that representation with covr reliably, so
    # artwork is extracted as a clean JPEG sidecar in this explicit ABS-only mode.
    if plan.keep_cover and plan.expected.has_cover:
        extract_cover(plan.expected, cover_file, plan.input_decoder)
        cover_sidecar = cover_file

    encode_or_remux(plan, audio_only)
    if progress is not None:
        action_word = "Remux" if plan.action == RepairAction.REMUX else "Encode"
        progress.stage(f"{action_word} complete; checking QT metadata output...")

    after_mux = probe_file(audio_only)
    missing, mismatched = compare_tags(plan.expected.tags, after_mux.tags)
    if mismatched:
        details = "; ".join(
            f"{key!r} changed {expected!r} -> {actual!r}"
            for key, expected, actual in mismatched
        )
        raise RepairError("QuickTime metadata values changed: " + details)
    if missing:
        metadata_sidecar = tempdir / "metadata.txt"
        write_metadata_sidecar(metadata_sidecar, missing)
        warnings.append(
            f"{len(missing)} ffprobe-visible tag(s) are not represented in-file and will be written to sidecar"
        )

    return audio_only, metadata_sidecar, cover_sidecar, warnings


def sidecar_destinations(plan: RepairPlan) -> tuple[Path, Path]:
    stem = plan.destination.with_suffix("")
    return Path(str(stem) + ".metadata.txt"), Path(str(stem) + ".jpg")


def commit_nonreplace(
    plan: RepairPlan,
    staged_audio: Path,
    metadata_sidecar: Path | None,
    cover_sidecar: Path | None,
) -> None:
    destination = plan.destination
    metadata_dst, cover_dst = sidecar_destinations(plan)

    collisions = [path for path in (destination, metadata_dst if metadata_sidecar else None, cover_dst if cover_sidecar else None) if path is not None and path.exists()]
    if collisions:
        raise TransactionError(
            "refusing to overwrite existing output: " + ", ".join(str(path) for path in collisions)
        )

    moved_sidecars: list[Path] = []
    try:
        # Sidecars first, audio last.  The playable output does not become
        # visible until all preservation artifacts are already in place.
        if metadata_sidecar is not None:
            os.replace(metadata_sidecar, metadata_dst)
            moved_sidecars.append(metadata_dst)
        if cover_sidecar is not None:
            os.replace(cover_sidecar, cover_dst)
            moved_sidecars.append(cover_dst)
        os.replace(staged_audio, destination)
    except OSError as exc:
        for moved in moved_sidecars:
            try:
                moved.unlink()
            except OSError:
                pass
        raise TransactionError(f"could not commit output: {exc}") from exc


def create_backup_without_removing_source(
    source: Path,
    backup: Path,
    *,
    progress: ProgressReporter | None = None,
) -> str:
    """Create a no-clobber original backup while the live source stays in place.

    A hard link is ideal: it is atomic, byte-identical, uses negligible space,
    and leaves the original pathname untouched.  Filesystems without hard-link
    support fall back to an exclusive byte-for-byte copy.
    """

    try:
        os.link(source, backup)
        if progress is not None:
            progress.stage("original backup created via hard link")
        return "hard link"
    except FileExistsError as exc:
        raise TransactionError(f"backup already exists; refusing replacement: {backup}") from exc
    except OSError as exc:
        # EPERM/EACCES/EOPNOTSUPP/ENOTSUP are common on network or unusual
        # filesystems.  Same-directory EXDEV is unlikely but harmless to treat
        # as a copy fallback.  Unexpected errors still get one safe copy attempt.
        link_error = exc

    free = shutil.disk_usage(source.parent).free
    required = source.stat().st_size + 64 * 1024 * 1024
    if free < required:
        raise TransactionError(
            f"hard-link backup unavailable ({link_error}); copy fallback needs "
            f"approximately {human_size(required)}, only {human_size(free)} free"
        )

    backup_created = False
    try:
        total_size = source.stat().st_size
        if progress is not None:
            progress.stage(f"creating .bak backup copy ({human_size(total_size)})...")
        copied = 0
        with source.open("rb") as src_handle:
            try:
                backup_handle = backup.open("xb")
                backup_created = True
            except FileExistsError as exc:
                raise TransactionError(
                    f"backup appeared during replacement preflight; refusing to overwrite it: {backup}"
                ) from exc
            with backup_handle:
                while True:
                    chunk = src_handle.read(16 * 1024 * 1024)
                    if not chunk:
                        break
                    backup_handle.write(chunk)
                    copied += len(chunk)
                    if progress is not None and total_size:
                        percent = min(100.0, copied * 100.0 / total_size)
                        progress.update(
                            f"creating .bak backup copy... {percent:5.1f}% "
                            f"({human_size(copied)}/{human_size(total_size)})"
                        )
                backup_handle.flush()
                os.fsync(backup_handle.fileno())
        if progress is not None:
            progress.finish_update()
        shutil.copystat(source, backup, follow_symlinks=True)
        return "copy"
    except TransactionError:
        raise
    except Exception as copy_exc:
        if backup_created:
            try:
                backup.unlink(missing_ok=True)
            except OSError:
                pass
        raise TransactionError(
            f"could not create safe backup (hard-link error: {link_error}; copy error: {copy_exc})"
        ) from copy_exc


def commit_replace(
    plan: RepairPlan,
    staged_audio: Path,
    metadata_sidecar: Path | None,
    cover_sidecar: Path | None,
    *,
    progress: ProgressReporter | None = None,
) -> None:
    source = plan.source
    backup = source.with_name(source.name + ".bak")
    metadata_dst, cover_dst = sidecar_destinations(plan)

    if backup.exists():
        raise TransactionError(f"backup already exists; refusing replacement: {backup}")

    sidecar_collisions = [
        path
        for path in (
            metadata_dst if metadata_sidecar is not None else None,
            cover_dst if cover_sidecar is not None else None,
        )
        if path is not None and path.exists()
    ]
    if sidecar_collisions:
        raise TransactionError(
            "refusing to overwrite existing sidecar(s): "
            + ", ".join(str(path) for path in sidecar_collisions)
        )

    # Crucially, creating the backup does not move the original.  The expected
    # source pathname remains valid until the one atomic os.replace() that
    # installs the already-verified output.
    backup_method = create_backup_without_removing_source(source, backup, progress=progress)

    moved_sidecars: list[Path] = []
    try:
        if metadata_sidecar is not None:
            os.replace(metadata_sidecar, metadata_dst)
            moved_sidecars.append(metadata_dst)
        if cover_sidecar is not None:
            os.replace(cover_sidecar, cover_dst)
            moved_sidecars.append(cover_dst)

        os.replace(staged_audio, source)
    except Exception as exc:
        # If install failed, source was never removed; discard the newly-made
        # backup/sidecars to return to the pre-commit state.
        for moved in moved_sidecars:
            try:
                moved.unlink()
            except OSError:
                pass
        try:
            backup.unlink()
        except OSError:
            pass
        if isinstance(exc, TransactionError):
            raise
        raise TransactionError(f"replacement commit failed; original remains in place: {exc}") from exc

    # Record the method in a harmless extended-free way by attaching it to the
    # plan is not possible (frozen dataclass); the caller's success message uses
    # the stable backup path rather than depending on implementation details.
    _ = backup_method


def repair_transaction(
    plan: RepairPlan,
    *,
    atomicparsley: str | None,
    progress: ProgressReporter | None = None,
) -> RepairOutcome:
    destination_parent = plan.destination.parent
    destination_parent.mkdir(parents=True, exist_ok=True)
    ensure_free_space(plan, destination_parent)

    try:
        with tempfile.TemporaryDirectory(prefix=".m4bcheck-", dir=destination_parent) as temp_name:
            tempdir = Path(temp_name)
            staged_audio, metadata_sidecar, cover_sidecar, warnings = stage_repair(
                plan,
                tempdir,
                atomicparsley=atomicparsley,
                progress=progress,
            )

            expect_embedded_cover = (
                plan.tag_mode == "standard" and plan.keep_cover and plan.expected.has_cover
            )
            verification = verify_output(
                plan,
                staged_audio,
                expect_embedded_cover=expect_embedded_cover,
                progress=progress,
            )
            if not verification.ok:
                raise VerificationError("; ".join(verification.failures))

            if progress is not None:
                progress.stage("verification passed; committing output...")

            if plan.replace:
                commit_replace(
                    plan,
                    staged_audio,
                    metadata_sidecar,
                    cover_sidecar,
                    progress=progress,
                )
                message = f"replaced original; backup at {plan.source.name}.bak"
                destination = plan.source
            else:
                commit_nonreplace(plan, staged_audio, metadata_sidecar, cover_sidecar)
                message = "repair committed"
                destination = plan.destination

            if warnings:
                message += "; " + "; ".join(warnings)
            return RepairOutcome(plan.source, destination, True, message, verification)

    except M4BCheckError as exc:
        return RepairOutcome(plan.source, None, False, str(exc), None)
    except OSError as exc:
        return RepairOutcome(plan.source, None, False, f"filesystem error: {exc}", None)


