def interactive_terminal(stream: object = sys.stdout) -> bool:
    return bool(hasattr(stream, "isatty") and stream.isatty())


def color_enabled(stream: object = sys.stdout) -> bool:
    """Use color only for an interactive terminal and honor the NO_COLOR convention."""

    return bool("NO_COLOR" not in os.environ and interactive_terminal(stream))


def style(text: str, *codes: str, stream: object = sys.stdout) -> str:
    if not color_enabled(stream) or not codes:
        return text
    return "".join(codes) + text + ANSI_RESET


def report_label(text: str) -> str:
    """Color a fixed-width report label without ANSI escapes breaking alignment."""

    return style(f"{text:<11}", ANSI_BLUE)


class ProgressReporter:
    """Small terminal progress surface for post-encode work.

    ffmpeg already shows its own encoding stats.  The expensive work after that
    used to be silent: metadata splicing, a full decode verification, and up to
    dozens of chapter-seek checks.  The first post-encode stage starts one
    cumulative timer; every subsequent cyan stage/update shows elapsed time from
    that same origin so the user can see both activity and total verification
    overhead without each sub-step resetting its clock.
    """

    def __init__(self) -> None:
        self._transient_width = 0
        self._started: float | None = None

    def _elapsed_text(self) -> str:
        if self._started is None:
            self._started = time.monotonic()
        elapsed = max(0.0, time.monotonic() - self._started)
        return human_time(elapsed)

    def _line(self, message: str) -> str:
        return f"    → [{self._elapsed_text()}] {message}"

    def _clear_transient(self) -> None:
        if self._transient_width and interactive_terminal(sys.stdout):
            sys.stdout.write("\r" + (" " * self._transient_width) + "\r")
            sys.stdout.flush()
        self._transient_width = 0

    def stage(self, message: str) -> None:
        self._clear_transient()
        print(style(self._line(message), ANSI_CYAN), flush=True)

    def update(self, message: str) -> None:
        # Carriage-return animation is useful on a terminal but undesirable in
        # redirected logs.  Stage messages still provide breadcrumbs there.
        if not interactive_terminal(sys.stdout):
            return
        plain = self._line(message)
        rendered = style(plain, ANSI_CYAN)
        padding = " " * max(0, self._transient_width - len(plain))
        sys.stdout.write("\r" + rendered + padding)
        sys.stdout.flush()
        self._transient_width = len(plain)

    def finish_update(self) -> None:
        if self._transient_width:
            sys.stdout.write("\n")
            sys.stdout.flush()
            self._transient_width = 0


def human_size(byte_count: int | float) -> str:
    value = float(max(byte_count, 0))
    units = ("B", "KB", "MB", "GB", "TB")
    unit = units[0]
    for unit in units:
        if value < 1024.0 or unit == units[-1]:
            break
        value /= 1024.0
    if unit == "B":
        return f"{int(value)} {unit}"
    return f"{value:.1f} {unit}"


def human_time(seconds: float | None) -> str:
    if seconds is None or not math.isfinite(seconds) or seconds < 0:
        return "?"
    total = int(seconds)
    hours, remainder = divmod(total, 3600)
    minutes, secs = divmod(remainder, 60)
    return f"{hours}:{minutes:02d}:{secs:02d}"


def compact_error(stderr: str, limit: int = 360) -> str:
    text = " ".join(stderr.strip().split())
    if len(text) <= limit:
        return text
    return text[: limit - 1] + "…"


def run_capture(
    args: Sequence[str],
    *,
    check: bool = False,
    text: bool = True,
    timeout: float | None = None,
) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            list(args),
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=text,
            check=check,
            timeout=timeout,
        )
    except FileNotFoundError as exc:
        raise M4BCheckError(f"required executable not found: {args[0]}") from exc
    except subprocess.TimeoutExpired as exc:
        raise M4BCheckError(f"command timed out: {args[0]}") from exc


