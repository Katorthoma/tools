def decode_test(path: Path, decoder: DecoderKind, seconds: float = DECODER_TEST_SECONDS) -> tuple[int, bytes, str]:
    """Decode from position zero and require actual PCM output.

    ffmpeg can occasionally return success for an unsupported stream while
    producing no decoded frames.  That is not a usable decoder.  Emitting a
    small mono/8 kHz PCM stream makes the capability test match what we really
    need: decoded audio, not merely an exit status.
    """

    args = ["ffmpeg", "-hide_banner", "-v", "error"]
    if decoder == DecoderKind.AAC_AT:
        # Input-side decoder selection must appear before -i.  This is the
        # critical xHE-AAC/USAC workaround on macOS.
        args += ["-c:a", "aac_at"]
    args += [
        "-i",
        str(path),
        "-map",
        "0:a:0",
        "-t",
        f"{seconds:.3f}",
        "-ac",
        "1",
        "-ar",
        "8000",
        "-f",
        "s16le",
        "pipe:1",
    ]
    try:
        result = subprocess.run(
            args,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
    except FileNotFoundError as exc:
        raise M4BCheckError("required executable not found: ffmpeg") from exc
    stderr = result.stderr.decode("utf-8", errors="replace")
    return result.returncode, result.stdout, stderr


def detect_decoder(
    probe: ProbeResult,
    *,
    aac_at_available: bool,
) -> DecoderResult:
    """Choose a decoder that demonstrably emits audio from position zero.

    Ordinary AAC stays on ffmpeg's native decoder.  xHE-AAC/USAC is the one
    deliberate exception on macOS: when AudioToolbox is available and can
    decode the stream, select aac_at even if the native decoder manages to emit
    an initial frame.  Native ffmpeg's incomplete USAC implementation can fail
    later in the book, while AudioToolbox is the established repair path.
    """

    native_rc, native_pcm, native_stderr = decode_test(probe.path, DecoderKind.NATIVE)
    native_ok = native_rc == 0 and bool(native_pcm)
    native_error = compact_error(native_stderr)
    if native_rc == 0 and not native_pcm:
        native_error = (native_error + "; " if native_error else "") + "decoder emitted no PCM audio"

    xhe = looks_like_xhe(probe.profile, probe.codec)
    if xhe and aac_at_available:
        apple_rc, apple_pcm, apple_stderr = decode_test(probe.path, DecoderKind.AAC_AT)
        apple_ok = apple_rc == 0 and bool(apple_pcm)
        apple_error = compact_error(apple_stderr)
        if apple_rc == 0 and not apple_pcm:
            apple_error = (apple_error + "; " if apple_error else "") + "decoder emitted no PCM audio"
        if apple_ok:
            return DecoderResult(
                DecoderKind.AAC_AT,
                native_error=native_error,
                aac_at_error=apple_error,
            )
        if native_ok:
            # Keep this repairable only if native truly emitted audio.  The full
            # encode remains authoritative and the transaction will not commit
            # anything that fails verification.
            return DecoderResult(
                DecoderKind.NATIVE,
                native_error=native_error,
                aac_at_error=apple_error,
            )
        return DecoderResult(
            DecoderKind.NONE,
            native_error=native_error,
            aac_at_error=apple_error,
        )

    if native_ok:
        return DecoderResult(DecoderKind.NATIVE, native_error=native_error)

    if not aac_at_available:
        return DecoderResult(DecoderKind.NONE, native_error=native_error)

    apple_rc, apple_pcm, apple_stderr = decode_test(probe.path, DecoderKind.AAC_AT)
    apple_ok = apple_rc == 0 and bool(apple_pcm)
    apple_error = compact_error(apple_stderr)
    if apple_rc == 0 and not apple_pcm:
        apple_error = (apple_error + "; " if apple_error else "") + "decoder emitted no PCM audio"
    if apple_ok:
        return DecoderResult(
            DecoderKind.AAC_AT,
            native_error=native_error,
            aac_at_error=apple_error,
        )

    return DecoderResult(
        DecoderKind.NONE,
        native_error=native_error,
        aac_at_error=apple_error,
    )

def _stereo_sample_windows(duration: float) -> list[tuple[str, float, float]]:
    """Choose short windows distributed from the opening to the ending.

    The opening and ending windows are explicit because songs, publisher
    bumpers, and credits often live there.  Five percentage-based windows then
    cover the body of the book.  Overlapping windows are deduplicated for short
    inputs.
    """

    if duration <= 0:
        return []

    window = min(STEREO_SAMPLE_SECONDS, max(5.0, duration / 10.0))
    half = window / 2.0
    candidates: list[tuple[str, float]] = []

    # Keep the first sample away from absolute 00:00 when possible so a silent
    # lead-in does not dominate the measurement.
    early_center = min(duration / 2.0, 75.0 if duration > 180.0 else max(half, duration * 0.10))
    candidates.append(("opening", early_center))
    for fraction in STEREO_SAMPLE_FRACTIONS:
        candidates.append((f"{int(fraction * 100)}%", duration * fraction))
    late_center = max(duration / 2.0, duration - 75.0 if duration > 180.0 else duration * 0.90)
    candidates.append(("ending", late_center))

    windows: list[tuple[str, float, float]] = []
    seen_starts: list[float] = []
    for label, center in candidates:
        start = max(0.0, min(duration - window, center - half))
        end = min(duration, start + window)
        if end <= start:
            continue
        # Deduplicate windows that collapse together on short files.
        if any(abs(start - previous) < max(1.0, window * 0.25) for previous in seen_starts):
            continue
        seen_starts.append(start)
        windows.append((label, start, end))
    return windows


def _measure_stereo_window(
    probe: ProbeResult,
    decoder: DecoderKind,
    label: str,
    start: float,
    end: float,
) -> StereoSample:
    """Measure one window using a fast input-side seek.

    For xHE-AAC this deliberately uses the decoder selected by capability
    probing, normally AudioToolbox on macOS.  An arbitrary seek can still fail
    on unusual USAC streams.  A failed window is therefore *not* interpreted as
    mono: it makes the advisory analysis incomplete and suppresses the mono
    recommendation.
    """

    args = ["ffmpeg", "-hide_banner", "-nostats", "-v", "info"]
    if decoder == DecoderKind.AAC_AT:
        args += ["-c:a", "aac_at"]
    args += [
        "-ss",
        f"{start:.6f}",
        "-i",
        str(probe.path),
        "-map",
        "0:a:0",
        "-t",
        f"{max(0.0, end - start):.6f}",
        "-af",
        "pan=mono|c0=c0-c1,volumedetect",
        "-f",
        "null",
        "-",
    ]
    result = run_capture(args)
    combined = f"{result.stdout}\n{result.stderr}"
    matches = re.findall(
        r"mean_volume:\s*(-?inf|-?\d+(?:\.\d+)?)\s*dB",
        combined,
        re.IGNORECASE,
    )
    if result.returncode != 0 or not matches:
        reason = compact_error(result.stderr)
        if result.returncode == 0 and not reason:
            reason = "volumedetect did not report mean_volume"
        elif not reason:
            reason = f"ffmpeg exited {result.returncode}"
        return StereoSample(label, start, end, None, reason)

    raw = matches[-1].lower()
    value = float("-inf") if raw == "-inf" else float(raw)
    return StereoSample(label, start, end, value)


def stereo_delta(probe: ProbeResult, decoder: DecoderKind) -> StereoAnalysis:
    """Sample stereo difference at several points across the audiobook.

    This replaces the old single 60-180 second measurement.  It is designed to
    catch occasional stereo material such as songs or dramatized segments while
    keeping a library scan fast.  It still cannot prove that every unsampled
    second is dual-mono, so automatic downmixing remains forbidden.
    """

    if probe.channels != 2:
        return StereoAnalysis(())

    windows = _stereo_sample_windows(probe.audio_duration)
    if not windows:
        return StereoAnalysis((), "no usable analysis windows")

    samples = tuple(
        _measure_stereo_window(probe, decoder, label, start, end)
        for label, start, end in windows
    )
    if not any(sample.mean_delta_db is not None for sample in samples):
        return StereoAnalysis(samples, "all distributed stereo-analysis windows failed")
    return StereoAnalysis(samples)


