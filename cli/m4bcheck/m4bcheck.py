def chapter_equivalent(expected: ChapterInfo, actual: ChapterInfo) -> tuple[bool, str | None]:
    if abs(expected.start - actual.start) > CHAPTER_TIME_TOLERANCE:
        return False, f"start changed {expected.start:.6f}s -> {actual.start:.6f}s"
    if abs(expected.end - actual.end) > CHAPTER_TIME_TOLERANCE:
        return False, f"end changed {expected.end:.6f}s -> {actual.end:.6f}s"
    if expected.title != actual.title:
        return False, f"title changed {expected.title!r} -> {actual.title!r}"
    return True, None


def full_decode_verify(
    path: Path,
    *,
    progress: ProgressReporter | None = None,
) -> tuple[bool, str]:
    args = [
        "ffmpeg",
        "-hide_banner",
        "-v",
        "error",
        "-xerror",
        "-i",
        str(path),
        "-map",
        "0:a:0",
        "-f",
        "null",
        "-",
    ]

    # This verification intentionally decodes the entire audiobook.  On a
    # 19-hour title it can take long enough that a silent subprocess looks hung.
    # ProgressReporter owns the cumulative post-encode timer; this loop simply
    # refreshes the active status line while preserving ffmpeg's exit semantics.
    try:
        process = subprocess.Popen(
            args,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.PIPE,
            text=True,
        )
    except FileNotFoundError as exc:
        raise M4BCheckError("required executable not found: ffmpeg") from exc

    last_tick = -1
    while process.poll() is None:
        tick = int(time.monotonic())
        if progress is not None and tick != last_tick:
            progress.update("verifying full audio decode to EOF...")
            last_tick = tick
        time.sleep(0.2)

    stderr = process.stderr.read() if process.stderr is not None else ""
    returncode = process.wait()
    if progress is not None:
        progress.finish_update()

    if returncode == 0:
        return True, "full audio stream decodes to EOF"
    return False, compact_error(stderr) or f"full decode exited {returncode}"


def chapter_seek_verify(
    path: Path,
    chapters: Sequence[ChapterInfo],
    duration: float,
    *,
    progress: ProgressReporter | None = None,
) -> tuple[bool, str]:
    """Exercise the actual ABS failure mode at every chapter start.

    -ss is intentionally input-side: this asks the MP4/AAC stack to perform a
    random-access seek before decoding.  A small low-rate PCM capture must be
    produced, so an exit-0 decode that emitted no audio is not accepted.
    """

    for index, chapter in enumerate(chapters, start=1):
        if progress is not None:
            progress.update(
                f"verifying random-access chapter seeks... {index}/{len(chapters)}"
            )
        remaining = duration - chapter.start
        if remaining <= 0:
            progress.finish_update() if progress is not None else None
            return False, f"chapter {index} starts at/past end of audio"
        sample_seconds = min(SEEK_TEST_SECONDS, remaining)
        args = [
            "ffmpeg",
            "-hide_banner",
            "-v",
            "error",
            "-xerror",
            "-ss",
            f"{chapter.start:.6f}",
            "-i",
            str(path),
            "-map",
            "0:a:0",
            "-t",
            f"{sample_seconds:.6f}",
            "-ac",
            "1",
            "-ar",
            "8000",
            "-f",
            "s16le",
            "pipe:1",
        ]
        try:
            result = subprocess.run(
                args,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                check=False,
            )
        except FileNotFoundError as exc:
            raise M4BCheckError("required executable not found: ffmpeg") from exc
        if result.returncode != 0:
            stderr = result.stderr.decode("utf-8", errors="replace")
            progress.finish_update() if progress is not None else None
            return False, f"chapter {index} seek/decode failed: {compact_error(stderr)}"
        if not result.stdout:
            progress.finish_update() if progress is not None else None
            return False, f"chapter {index} seek produced no decoded audio"
    if progress is not None:
        progress.finish_update()
    return True, f"random-access decode succeeded at all {len(chapters)} chapter start(s)"


def verify_output(
    plan: RepairPlan,
    output: Path,
    *,
    expect_embedded_cover: bool,
    progress: ProgressReporter | None = None,
) -> VerificationResult:
    checks: list[str] = []
    failures: list[str] = []
    warnings: list[str] = []

    if progress is not None:
        progress.stage("verifying container, chapters, metadata, and cover...")

    try:
        out_probe = probe_file(output)
    except ProbeError as exc:
        return VerificationResult(False, tuple(checks), (str(exc),), tuple(warnings), None)

    if plan.action == RepairAction.ENCODE:
        if out_probe.codec.casefold() != "aac" or out_probe.profile.casefold() != "lc":
            failures.append(
                f"output audio is {out_probe.codec!r}/{out_probe.profile!r}, expected AAC-LC"
            )
        else:
            checks.append("AAC-LC codec/profile verified")

    expected_channels = 1 if plan.mono and plan.action == RepairAction.ENCODE else plan.expected.channels
    if out_probe.channels != expected_channels:
        failures.append(
            f"channel count changed unexpectedly: expected {expected_channels}, got {out_probe.channels}"
        )
    else:
        checks.append(f"channel count verified ({out_probe.channels})")

    duration_delta = abs(out_probe.audio_duration - plan.expected.audio_duration)
    if duration_delta > VERIFY_DURATION_TOLERANCE:
        failures.append(
            f"audio duration changed by {duration_delta:.3f}s "
            f"({human_time(plan.expected.audio_duration)} -> {human_time(out_probe.audio_duration)})"
        )
    else:
        checks.append(f"audio duration preserved within {duration_delta:.3f}s")

    if out_probe.format_duration is not None:
        container_delta = abs(out_probe.format_duration - out_probe.audio_duration)
        if container_delta > VERIFY_DURATION_TOLERANCE:
            failures.append(
                f"output container duration differs from output audio by {container_delta:.3f}s"
            )
        else:
            checks.append("output container/audio durations agree")
    else:
        failures.append("output container duration is unreadable")

    expected_chapters = plan.expected.chapters
    actual_chapters = out_probe.chapters
    if len(actual_chapters) != len(expected_chapters):
        failures.append(
            f"chapter count changed: {len(expected_chapters)} -> {len(actual_chapters)}"
        )
    else:
        chapter_failure = False
        for index, (expected, actual) in enumerate(zip(expected_chapters, actual_chapters), start=1):
            equivalent, reason = chapter_equivalent(expected, actual)
            if not equivalent:
                failures.append(f"chapter {index}: {reason}")
                chapter_failure = True
        if not chapter_failure:
            checks.append(f"all {len(expected_chapters)} chapter start/end/title records preserved")

    for index, chapter in enumerate(actual_chapters, start=1):
        if chapter.start < 0 or chapter.end < chapter.start:
            failures.append(f"output chapter {index} has an invalid time range")
        if chapter.end > out_probe.audio_duration + CHAPTER_END_TOLERANCE:
            failures.append(f"output chapter {index} ends past the audio stream")

    atom = out_probe.atom_scan
    if atom.error is not None:
        failures.append(f"output atom scan is indeterminate: {atom.error}")
    elif atom.fragmented:
        failures.append("output is fragmented MP4 (moof present), expected ordinary faststart M4B")
    elif atom.faststart is not True:
        failures.append("output moov atom is not before mdat")
    else:
        checks.append("faststart verified (moov before mdat)")

    if plan.tag_mode == "standard":
        # ffprobe cannot expose the complete Mp3tag state: the real audit file
        # contains native atoms ffprobe omits entirely and three repeated GENRE
        # freeform atoms that ffprobe collapses to one key.  Compare the opaque
        # moov.udta capsule instead.  This is a byte-for-byte check after
        # excluding only muxer-owned ©too and an explicitly omitted covr.
        try:
            source_capsule = metadata_capsule(plan.source, keep_cover=plan.keep_cover)
            output_capsule = metadata_capsule(output, keep_cover=plan.keep_cover)
        except RepairError as exc:
            failures.append(f"metadata capsule verification failed: {exc}")
        else:
            if source_capsule.normalized_udta != output_capsule.normalized_udta:
                failures.append(
                    "MP4 user metadata differs from source "
                    f"({source_capsule.digest[:12]} != {output_capsule.digest[:12]})"
                )
            else:
                checks.append(
                    f"exact MP4 user-data capsule preserved ({source_capsule.ilst_atom_count} ilst atom(s))"
                )
    else:
        # QT mode intentionally uses ffmpeg's mdta table for ABS-oriented use.
        # It cannot promise Mp3tag atom identity, but it must not change values
        # that ffprobe can read.
        missing_tags, mismatched_tags = compare_tags(plan.expected.tags, out_probe.tags)
        if mismatched_tags:
            failures.extend(
                f"metadata tag {key!r} changed {expected!r} -> {actual!r}"
                for key, expected, actual in mismatched_tags
            )
        if missing_tags:
            warnings.append(f"{len(missing_tags)} metadata tag(s) are not represented in QT output")
        if not mismatched_tags:
            checks.append("ffprobe-visible metadata values preserved in QT mode")

    if expect_embedded_cover:
        if not out_probe.has_cover:
            failures.append("embedded cover expected but no cover stream is present")
        else:
            checks.append("embedded cover verified")

    decoded, message = full_decode_verify(output, progress=progress)
    if decoded:
        checks.append(message)
    else:
        failures.append(f"full output decode failed: {message}")

    if not failures and expected_chapters:
        seek_ok, seek_message = chapter_seek_verify(
            output,
            actual_chapters,
            out_probe.audio_duration,
            progress=progress,
        )
        if seek_ok:
            checks.append(seek_message)
        else:
            failures.append(seek_message)

    return VerificationResult(
        ok=not failures,
        checks=tuple(checks),
        failures=tuple(failures),
        warnings=tuple(warnings),
        output_probe=out_probe,
    )


