"""
m4bcheck v2.2.7 — inspect and repair M4B audiobooks for Audiobookshelf.

Designed for Python 3.10+, with development and primary testing on Python 3.12,
macOS/Homebrew ffmpeg 9.x with AudioToolbox, and Linux ffmpeg builds.  No third-party Python packages are required.

The repair pipeline is intentionally transactional:

    probe -> diagnose -> plan -> stage -> verify -> commit

No staged file is moved to its final pathname until every mandatory
verification has passed. Standard tag mode preserves the source moov.udta user-data
capsule byte-for-byte (except the muxer-owned encoder atom and an explicitly
omitted cover), which avoids ffprobe's lossy view of repeated/native Mp3tag tags.
With --replace, a no-clobber .bak is created while the original pathname remains
live; only then is the verified staged output atomically installed.  --replace-fixed
is a separate commit operation for an already-created ``[Fixed ...]`` sibling: it
re-runs the complete verification gate, creates the same no-clobber .bak, and then
atomically promotes that verified sibling to the original filename without encoding.
"""

