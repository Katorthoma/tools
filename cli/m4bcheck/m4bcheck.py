# MP4 top-level atom walker


def scan_mp4_atoms(path: Path, *, max_boxes: int = 100_000) -> AtomScan:
    """Walk top-level ISO BMFF boxes using seek, not a linear file scan.

    Handles 32-bit sizes, 64-bit largesize boxes, and size==0 (extends to EOF).
    Malformed sizes are reported as an indeterminate scan instead of silently
    being treated as faststart.  `moof` is recorded because +faststart is not a
    meaningful classification for fragmented MP4.
    """

    file_size = path.stat().st_size
    offset = 0
    count = 0
    moov_offset: int | None = None
    mdat_offset: int | None = None
    fragmented = False
    boxes: list[str] = []

    try:
        with path.open("rb") as handle:
            while offset < file_size:
                count += 1
                if count > max_boxes:
                    return AtomScan(
                        moov_offset,
                        mdat_offset,
                        fragmented,
                        tuple(boxes),
                        f"more than {max_boxes} top-level boxes",
                    )

                if file_size - offset < 8:
                    return AtomScan(
                        moov_offset,
                        mdat_offset,
                        fragmented,
                        tuple(boxes),
                        f"truncated box header at byte {offset}",
                    )

                handle.seek(offset)
                header = handle.read(8)
                size32, type_bytes = struct.unpack(">I4s", header)
                try:
                    box_type = type_bytes.decode("ascii")
                except UnicodeDecodeError:
                    box_type = type_bytes.decode("latin-1")
                boxes.append(box_type)

                header_size = 8
                if size32 == 1:
                    extended = handle.read(8)
                    if len(extended) != 8:
                        return AtomScan(
                            moov_offset,
                            mdat_offset,
                            fragmented,
                            tuple(boxes),
                            f"truncated largesize for {box_type!r} at byte {offset}",
                        )
                    size = struct.unpack(">Q", extended)[0]
                    header_size = 16
                elif size32 == 0:
                    size = file_size - offset
                else:
                    size = size32

                if size < header_size:
                    return AtomScan(
                        moov_offset,
                        mdat_offset,
                        fragmented,
                        tuple(boxes),
                        f"invalid size {size} for {box_type!r} at byte {offset}",
                    )

                end = offset + size
                if end > file_size:
                    return AtomScan(
                        moov_offset,
                        mdat_offset,
                        fragmented,
                        tuple(boxes),
                        f"box {box_type!r} at byte {offset} extends past EOF",
                    )

                if box_type == "moov" and moov_offset is None:
                    moov_offset = offset
                elif box_type == "mdat" and mdat_offset is None:
                    mdat_offset = offset
                elif box_type == "moof":
                    fragmented = True

                if size32 == 0:
                    # By definition this box consumes the rest of the file.
                    break
                offset = end

    except OSError as exc:
        return AtomScan(
            moov_offset,
            mdat_offset,
            fragmented,
            tuple(boxes),
            f"atom scan failed: {exc}",
        )

    if moov_offset is None:
        return AtomScan(
            moov_offset,
            mdat_offset,
            fragmented,
            tuple(boxes),
            "no top-level moov atom found",
        )
    if mdat_offset is None:
        return AtomScan(
            moov_offset,
            mdat_offset,
            fragmented,
            tuple(boxes),
            "no top-level mdat atom found",
        )

    return AtomScan(moov_offset, mdat_offset, fragmented, tuple(boxes), None)


# ---------------------------------------------------------------------------
# Exact MP4 user-data capsule handling

# The real Mp3tag audit showed why ffprobe JSON alone is insufficient for
# metadata preservation: several native iTunes atoms are not exposed at all,
# and repeated freeform tags such as GENRE collapse to one dictionary value.
# Standard mode therefore treats moov.udta as an opaque capsule and transplants
# it after ffmpeg has finished the audio/container work.  The only ilst item we
# intentionally do not preserve is ©too (the muxer's encoder tag).  covr is
# preserved byte-for-byte unless --no-cover was requested.

_CONTAINER_CHILD_PREFIX: dict[bytes, int] = {
    b"moov": 0,
    b"trak": 0,
    b"mdia": 0,
    b"minf": 0,
    b"stbl": 0,
    b"edts": 0,
    b"dinf": 0,
    b"udta": 0,
    b"meta": 4,  # FullBox version/flags precede meta's child boxes.
}
_ILST_ENCODER = b"\xa9too"
_ILST_COVER = b"covr"
_ILST_PADDING = {b"free", b"skip"}


def _box_header(data: bytes, offset: int, end: int) -> BoxRef:
    if offset < 0 or end < offset or offset + 8 > end:
        raise RepairError(f"truncated MP4 box header at relative byte {offset}")
    size32, box_type = struct.unpack_from(">I4s", data, offset)
    header_size = 8
    if size32 == 1:
        if offset + 16 > end:
            raise RepairError(f"truncated largesize for MP4 box {box_type!r}")
        size = struct.unpack_from(">Q", data, offset + 8)[0]
        header_size = 16
    elif size32 == 0:
        size = end - offset
    else:
        size = size32
    if size < header_size:
        raise RepairError(f"invalid size {size} for MP4 box {box_type!r}")
    if offset + size > end:
        raise RepairError(f"MP4 box {box_type!r} extends past its parent")
    return BoxRef(offset, size, header_size, box_type)


def _child_boxes(box: bytes, *, prefix: int | None = None) -> tuple[BoxRef, ...]:
    root = _box_header(box, 0, len(box))
    child_prefix = _CONTAINER_CHILD_PREFIX.get(root.box_type, 0) if prefix is None else prefix
    offset = root.header_size + child_prefix
    children: list[BoxRef] = []
    while offset < len(box):
        child = _box_header(box, offset, len(box))
        children.append(child)
        offset = child.end
    if offset != len(box):
        raise RepairError(f"child boxes in {root.box_type!r} do not end on the parent boundary")
    return tuple(children)


def _box_bytes(box: bytes, ref: BoxRef) -> bytes:
    return box[ref.offset:ref.end]


def _build_box(box_type: bytes, payload: bytes, header_size: int = 8) -> bytes:
    if len(box_type) != 4:
        raise RepairError(f"invalid MP4 box type {box_type!r}")
    ordinary_size = 8 + len(payload)
    if header_size == 16 or ordinary_size > 0xFFFFFFFF:
        return struct.pack(">I4sQ", 1, box_type, 16 + len(payload)) + payload
    return struct.pack(">I4s", ordinary_size, box_type) + payload


def _find_child(box: bytes, wanted: bytes) -> BoxRef | None:
    for child in _child_boxes(box):
        if child.box_type == wanted:
            return child
    return None


def _extract_nested_box(root: bytes, path: Sequence[bytes]) -> bytes | None:
    if not path:
        return root
    current = root
    root_ref = _box_header(current, 0, len(current))
    if root_ref.box_type != path[0]:
        raise RepairError(f"expected MP4 root {path[0]!r}, found {root_ref.box_type!r}")
    for wanted in path[1:]:
        child = _find_child(current, wanted)
        if child is None:
            return None
        current = _box_bytes(current, child)
    return current


def _replace_or_append_child(parent: bytes, wanted: bytes, replacement: bytes) -> bytes:
    parent_ref = _box_header(parent, 0, len(parent))
    prefix = _CONTAINER_CHILD_PREFIX.get(parent_ref.box_type, 0)
    child = _find_child(parent, wanted)
    if child is None:
        payload = parent[parent_ref.header_size:] + replacement
    else:
        payload = (
            parent[parent_ref.header_size:child.offset]
            + replacement
            + parent[child.end:]
        )
    return _build_box(parent_ref.box_type, payload, parent_ref.header_size)


def _replace_nested_box(root: bytes, path: Sequence[bytes], replacement: bytes) -> bytes:
    if not path:
        return replacement
    root_ref = _box_header(root, 0, len(root))
    if root_ref.box_type != path[0]:
        raise RepairError(f"expected MP4 root {path[0]!r}, found {root_ref.box_type!r}")
    if len(path) == 1:
        return replacement

    child = _find_child(root, path[1])
    if child is None:
        if len(path) == 2:
            return _replace_or_append_child(root, path[1], replacement)
        raise RepairError(f"required MP4 path component {path[1]!r} is missing")
    rebuilt_child = _replace_nested_box(_box_bytes(root, child), path[1:], replacement)
    payload = root[root_ref.header_size:child.offset] + rebuilt_child + root[child.end:]
    return _build_box(root_ref.box_type, payload, root_ref.header_size)


def _read_top_level_box(path: Path, wanted: bytes) -> tuple[int, bytes]:
    file_size = path.stat().st_size
    offset = 0
    with path.open("rb") as handle:
        while offset < file_size:
            if file_size - offset < 8:
                raise RepairError(f"truncated top-level box header in {path.name}")
            handle.seek(offset)
            first = handle.read(16)
            if len(first) < 8:
                raise RepairError(f"could not read top-level MP4 box in {path.name}")
            size32, box_type = struct.unpack_from(">I4s", first, 0)
            header_size = 8
            if size32 == 1:
                if len(first) < 16:
                    raise RepairError(f"truncated largesize box in {path.name}")
                size = struct.unpack_from(">Q", first, 8)[0]
                header_size = 16
            elif size32 == 0:
                size = file_size - offset
            else:
                size = size32
            if size < header_size or offset + size > file_size:
                raise RepairError(f"invalid top-level {box_type!r} box in {path.name}")
            if box_type == wanted:
                handle.seek(offset)
                data = handle.read(size)
                if len(data) != size:
                    raise RepairError(f"short read of {wanted!r} from {path.name}")
                return offset, data
            if size32 == 0:
                break
            offset += size
    raise RepairError(f"no top-level {wanted!r} box found in {path.name}")


def _filtered_ilst(
    ilst: bytes,
    *,
    keep_cover: bool,
    replacement_encoder_atoms: Sequence[bytes] = (),
) -> bytes:
    root = _box_header(ilst, 0, len(ilst))
    if root.box_type != b"ilst":
        raise RepairError("metadata capsule does not contain an ilst box")
    pieces: list[bytes] = []
    encoder_inserted = False
    for child in _child_boxes(ilst, prefix=0):
        if child.box_type in _ILST_PADDING:
            continue
        if child.box_type == _ILST_ENCODER:
            if not encoder_inserted:
                pieces.extend(replacement_encoder_atoms)
                encoder_inserted = True
            continue
        if child.box_type == _ILST_COVER and not keep_cover:
            continue
        pieces.append(_box_bytes(ilst, child))
    if not encoder_inserted:
        pieces.extend(replacement_encoder_atoms)
    return _build_box(b"ilst", b"".join(pieces), root.header_size)


def _encoder_atoms(udta: bytes | None) -> tuple[bytes, ...]:
    if udta is None:
        return ()
    ilst = _extract_nested_box(udta, (b"udta", b"meta", b"ilst"))
    if ilst is None:
        return ()
    return tuple(
        _box_bytes(ilst, child)
        for child in _child_boxes(ilst, prefix=0)
        if child.box_type == _ILST_ENCODER
    )


def _normalized_udta_from_moov(moov: bytes, *, keep_cover: bool) -> bytes | None:
    udta = _extract_nested_box(moov, (b"moov", b"udta"))
    if udta is None:
        return None
    ilst = _extract_nested_box(udta, (b"udta", b"meta", b"ilst"))
    if ilst is None:
        return udta
    normalized_ilst = _filtered_ilst(ilst, keep_cover=keep_cover)
    return _replace_nested_box(udta, (b"udta", b"meta", b"ilst"), normalized_ilst)


def metadata_capsule(path: Path, *, keep_cover: bool) -> MetadataCapsule:
    _, moov = _read_top_level_box(path, b"moov")
    normalized = _normalized_udta_from_moov(moov, keep_cover=keep_cover)
    if normalized is None:
        return MetadataCapsule(None, hashlib.sha256(b"").hexdigest(), 0, 0)

    ilst = _extract_nested_box(normalized, (b"udta", b"meta", b"ilst"))
    atom_count = 0
    cover_count = 0
    if ilst is not None:
        children = _child_boxes(ilst, prefix=0)
        atom_count = sum(1 for child in children if child.box_type not in _ILST_PADDING)
        cover_count = sum(1 for child in children if child.box_type == _ILST_COVER)
    return MetadataCapsule(
        normalized,
        hashlib.sha256(normalized).hexdigest(),
        atom_count,
        cover_count,
    )


def _adjust_chunk_offsets(box: bytes, delta: int) -> bytes:
    """Adjust absolute stco/co64 offsets after changing faststart moov size.

    Standard non-fragmented MP4 locates media chunks through stco/co64 entries.
    Replacing moov.udta changes the byte position of the following mdat, so every
    chunk offset must move by the same delta.  We deliberately refuse a 32-bit
    stco overflow rather than silently corrupting a >4 GiB file.
    """

    root = _box_header(box, 0, len(box))
    if root.box_type in {b"stco", b"co64"}:
        payload = bytearray(box[root.header_size:])
        if len(payload) < 8:
            raise RepairError(f"short {root.box_type!r} chunk-offset box")
        count = struct.unpack_from(">I", payload, 4)[0]
        width = 4 if root.box_type == b"stco" else 8
        needed = 8 + count * width
        if len(payload) < needed:
            raise RepairError(f"truncated {root.box_type!r} chunk-offset table")
        fmt = ">I" if width == 4 else ">Q"
        maximum = 0xFFFFFFFF if width == 4 else 0xFFFFFFFFFFFFFFFF
        for index in range(count):
            entry_offset = 8 + index * width
            old = struct.unpack_from(fmt, payload, entry_offset)[0]
            new = old + delta
            if new < 0 or new > maximum:
                raise RepairError(
                    f"metadata transplant would overflow {root.box_type.decode('latin-1')} chunk offsets"
                )
            struct.pack_into(fmt, payload, entry_offset, new)
        return _build_box(root.box_type, bytes(payload), root.header_size)

    prefix = _CONTAINER_CHILD_PREFIX.get(root.box_type)
    if prefix is None:
        return box
    pieces: list[bytes] = [box[root.header_size:root.header_size + prefix]]
    for child in _child_boxes(box, prefix=prefix):
        pieces.append(_adjust_chunk_offsets(_box_bytes(box, child), delta))
    return _build_box(root.box_type, b"".join(pieces), root.header_size)


def _copy_n(source, destination, count: int, *, chunk_size: int = 8 * 1024 * 1024) -> None:
    remaining = count
    while remaining:
        block = source.read(min(chunk_size, remaining))
        if not block:
            raise RepairError("unexpected EOF while rewriting MP4 metadata")
        destination.write(block)
        remaining -= len(block)


def transplant_user_data(source: Path, target: Path, *, keep_cover: bool) -> MetadataCapsule:
    """Transplant source moov.udta into a staged faststart output.

    This is intentionally a binary transplant rather than a tag-name rewrite.
    It preserves Mp3tag-native atoms, repeated freeform atoms, unknown metadata,
    the redundant chpl chapter list, and cover bytes exactly.  The staged
    output's ©too encoder atom is retained because it describes the new mux.
    """

    source_moov_offset, source_moov = _read_top_level_box(source, b"moov")
    _ = source_moov_offset
    target_moov_offset, target_moov = _read_top_level_box(target, b"moov")
    target_scan = scan_mp4_atoms(target)
    if target_scan.error is not None or target_scan.fragmented or target_scan.faststart is not True:
        raise RepairError("metadata transplant requires a verified non-fragmented faststart staging file")

    source_udta = _extract_nested_box(source_moov, (b"moov", b"udta"))
    target_udta = _extract_nested_box(target_moov, (b"moov", b"udta"))
    if source_udta is None:
        # No user-data capsule to preserve.  This is a valid state for a bare
        # M4B; leave the muxer's output metadata alone.
        return metadata_capsule(source, keep_cover=keep_cover)

    source_ilst = _extract_nested_box(source_udta, (b"udta", b"meta", b"ilst"))
    merged_udta = source_udta
    if source_ilst is not None:
        output_encoder_atoms = _encoder_atoms(target_udta)
        merged_ilst = _filtered_ilst(
            source_ilst,
            keep_cover=keep_cover,
            replacement_encoder_atoms=output_encoder_atoms,
        )
        merged_udta = _replace_nested_box(
            source_udta,
            (b"udta", b"meta", b"ilst"),
            merged_ilst,
        )
    elif not keep_cover:
        raise RepairError("--no-cover cannot be guaranteed because source udta has no parseable ilst")

    if target_udta is None:
        new_moov_unadjusted = _replace_or_append_child(target_moov, b"udta", merged_udta)
    else:
        new_moov_unadjusted = _replace_nested_box(target_moov, (b"moov", b"udta"), merged_udta)

    delta = len(new_moov_unadjusted) - len(target_moov)
    new_moov = _adjust_chunk_offsets(new_moov_unadjusted, delta)
    if len(new_moov) != len(new_moov_unadjusted):
        raise RepairError("chunk-offset adjustment unexpectedly changed moov size")

    rewrite = target.with_name(target.name + ".metadata-splice.tmp")
    rewrite.unlink(missing_ok=True)
    try:
        with target.open("rb") as input_handle, rewrite.open("xb") as output_handle:
            _copy_n(input_handle, output_handle, target_moov_offset)
            output_handle.write(new_moov)
            input_handle.seek(target_moov_offset + len(target_moov))
            shutil.copyfileobj(input_handle, output_handle, length=8 * 1024 * 1024)
        os.replace(rewrite, target)
    except Exception:
        rewrite.unlink(missing_ok=True)
        raise

    expected_capsule = metadata_capsule(source, keep_cover=keep_cover)
    actual_capsule = metadata_capsule(target, keep_cover=keep_cover)
    if expected_capsule.normalized_udta != actual_capsule.normalized_udta:
        raise RepairError(
            "exact MP4 user-data transplant verification failed "
            f"({expected_capsule.digest[:12]} != {actual_capsule.digest[:12]})"
        )
    return expected_capsule


