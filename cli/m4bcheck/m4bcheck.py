def parse_optional_float(value: object) -> float | None:
    if value is None:
        return None
    try:
        parsed = float(str(value))
    except (TypeError, ValueError):
        return None
    if not math.isfinite(parsed) or parsed < 0:
        return None
    return parsed


def parse_optional_int(value: object) -> int | None:
    if value is None:
        return None
    try:
        parsed = int(str(value))
    except (TypeError, ValueError):
        return None
    return parsed if parsed >= 0 else None


def parse_time_base(value: object) -> float | None:
    if not isinstance(value, str) or "/" not in value:
        return None
    numerator, denominator = value.split("/", 1)
    try:
        n = int(numerator)
        d = int(denominator)
    except ValueError:
        return None
    if d == 0:
        return None
    return n / d


def stream_duration(stream: Mapping[str, object]) -> float | None:
    direct = parse_optional_float(stream.get("duration"))
    if direct is not None:
        return direct
    duration_ts = parse_optional_int(stream.get("duration_ts"))
    time_base = parse_time_base(stream.get("time_base"))
    if duration_ts is not None and time_base is not None:
        duration = duration_ts * time_base
        if math.isfinite(duration) and duration >= 0:
            return duration
    return None


def chapter_time(chapter: Mapping[str, object], prefix: str) -> float | None:
    direct = parse_optional_float(chapter.get(f"{prefix}_time"))
    if direct is not None:
        return direct
    ticks = parse_optional_int(chapter.get(prefix))
    time_base = parse_time_base(chapter.get("time_base"))
    if ticks is not None and time_base is not None:
        value = ticks * time_base
        if math.isfinite(value) and value >= 0:
            return value
    return None


def normalized_tags(raw: object) -> dict[str, str]:
    if not isinstance(raw, Mapping):
        return {}
    tags: dict[str, str] = {}
    for key, value in raw.items():
        if isinstance(key, str) and value is not None:
            tags[key] = str(value)
    return tags


def probe_file(path: Path) -> ProbeResult:
    result = run_capture(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_format",
            "-show_streams",
            "-show_chapters",
            "-of",
            "json",
            str(path),
        ]
    )
    if result.returncode != 0:
        raise ProbeError(
            f"ffprobe failed for {path.name}: {compact_error(result.stderr) or f'exit {result.returncode}'}"
        )

    try:
        payload = json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        raise ProbeError(f"ffprobe returned invalid JSON for {path.name}: {exc}") from exc

    streams = payload.get("streams")
    if not isinstance(streams, list):
        raise ProbeError(f"ffprobe returned no stream list for {path.name}")

    audio_stream: Mapping[str, object] | None = None
    cover_stream_index: int | None = None
    for raw_stream in streams:
        if not isinstance(raw_stream, Mapping):
            continue
        codec_type = raw_stream.get("codec_type")
        if codec_type == "audio" and audio_stream is None:
            audio_stream = raw_stream
        if codec_type == "video" and cover_stream_index is None:
            disposition = raw_stream.get("disposition")
            attached = False
            if isinstance(disposition, Mapping):
                attached = parse_optional_int(disposition.get("attached_pic")) == 1
            # M4B files normally contain only an attached cover video stream.
            # Accept any video stream as a cover candidate, but remember its
            # actual stream index for extraction.
            if attached or raw_stream.get("codec_name") in {"mjpeg", "png", "webp"}:
                cover_stream_index = parse_optional_int(raw_stream.get("index"))
            elif cover_stream_index is None:
                cover_stream_index = parse_optional_int(raw_stream.get("index"))

    if audio_stream is None:
        raise ProbeError(f"no audio stream found in {path.name}")

    audio_duration = stream_duration(audio_stream)
    if audio_duration is None or audio_duration <= 0:
        raise ProbeError(
            f"audio-stream duration is missing or invalid in {path.name}; "
            "cannot safely diagnose or verify repairs"
        )

    codec = str(audio_stream.get("codec_name") or "")
    profile = str(audio_stream.get("profile") or "")
    channels = parse_optional_int(audio_stream.get("channels"))
    if not codec:
        raise ProbeError(f"audio codec is missing in ffprobe output for {path.name}")
    if channels is None or channels <= 0:
        raise ProbeError(f"channel count is missing or invalid for {path.name}")

    sample_rate = parse_optional_int(audio_stream.get("sample_rate"))
    bit_rate = parse_optional_int(audio_stream.get("bit_rate"))

    raw_format = payload.get("format")
    format_duration: float | None = None
    tags: dict[str, str] = {}
    if isinstance(raw_format, Mapping):
        format_duration = parse_optional_float(raw_format.get("duration"))
        tags = normalized_tags(raw_format.get("tags"))

    raw_chapters = payload.get("chapters")
    chapters: list[ChapterInfo] = []
    if isinstance(raw_chapters, list):
        for index, raw_chapter in enumerate(raw_chapters):
            if not isinstance(raw_chapter, Mapping):
                raise ProbeError(f"chapter {index + 1} is malformed in {path.name}")
            start = chapter_time(raw_chapter, "start")
            end = chapter_time(raw_chapter, "end")
            if start is None or end is None:
                raise ProbeError(
                    f"chapter {index + 1} has an unreadable start/end time in {path.name}"
                )
            chapter_tags = normalized_tags(raw_chapter.get("tags"))
            title = chapter_tags.get("title", "")
            chapters.append(ChapterInfo(start=start, end=end, title=title))

    return ProbeResult(
        path=path,
        codec=codec,
        profile=profile,
        channels=channels,
        sample_rate=sample_rate,
        bit_rate=bit_rate,
        audio_duration=audio_duration,
        format_duration=format_duration,
        chapters=tuple(chapters),
        has_cover=cover_stream_index is not None,
        cover_stream_index=cover_stream_index,
        tags=tags,
        size=path.stat().st_size,
        atom_scan=scan_mp4_atoms(path),
    )


