def decoder_input_args(decoder: DecoderKind) -> list[str]:
    if decoder == DecoderKind.AAC_AT:
        return ["-c:a", "aac_at"]
    return []


def extract_cover(source: ProbeResult, target: Path, decoder: DecoderKind) -> None:
    if source.cover_stream_index is None:
        raise RepairError("source was reported to have a cover but no cover stream index is available")

    args = ["ffmpeg", "-hide_banner", "-v", "error"]
    # Cover extraction does not decode audio, so the audio decoder override is
    # deliberately not supplied here.
    args += [
        "-i",
        str(source.path),
        "-map",
        f"0:{source.cover_stream_index}",
        "-frames:v",
        "1",
        "-f",
        "mjpeg",
        "-y",
        str(target),
    ]
    result = run_capture(args)
    if result.returncode != 0 or not target.exists() or target.stat().st_size == 0:
        raise RepairError(
            "cover extraction failed: " + (compact_error(result.stderr) or f"exit {result.returncode}")
        )


def encode_or_remux(plan: RepairPlan, target: Path) -> None:
    args: list[str] = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-stats", "-y"]
    args += decoder_input_args(plan.input_decoder)
    args += ["-i", str(plan.source), "-map", "0:a:0"]

    if plan.action == RepairAction.REMUX:
        args += ["-c:a", "copy"]
    else:
        args += ["-c:a", plan.output_encoder, "-b:a", plan.bitrate]
        if plan.mono:
            args += ["-ac", "1"]

    args += ["-map_metadata", "0", "-map_chapters", "0"]
    movflags = "+faststart"
    if plan.tag_mode == "qt":
        movflags += "+use_metadata_tags"
    args += ["-movflags", movflags, str(target)]

    result = run_visible(args)
    if result.returncode != 0 or not target.exists() or target.stat().st_size == 0:
        raise RepairError(f"ffmpeg {'remux' if plan.action == RepairAction.REMUX else 'encode'} failed (exit {result.returncode})")


def attach_cover(audio: Path, cover: Path, target: Path) -> None:
    """Attach a clean single-frame cover after the audio-only mux.

    The source Audible cover may claim a book-long duration and carry absurd
    packet timestamps.  Copying that stream directly from the original file can
    wedge the muxer, so the cover is first extracted to an ordinary JPEG and
    then introduced as a second, clean input here.
    """

    args = [
        "ffmpeg",
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-i",
        str(audio),
        "-i",
        str(cover),
        "-map",
        "0:a:0",
        "-map",
        "1:v:0",
        "-c",
        "copy",
        "-disposition:v:0",
        "attached_pic",
        "-map_metadata",
        "0",
        "-map_chapters",
        "0",
        "-movflags",
        "+faststart",
        str(target),
    ]
    result = run_capture(args)
    if result.returncode != 0 or not target.exists() or target.stat().st_size == 0:
        raise RepairError(
            "cover re-attach failed: " + (compact_error(result.stderr) or f"exit {result.returncode}")
        )


def ensure_free_space(plan: RepairPlan, staging_parent: Path) -> None:
    estimate = estimate_output_size(plan.expected, plan.action, plan.bitrate)

    # Standard mode temporarily holds the ffmpeg output plus a streamed copy
    # while its exact moov.udta metadata capsule is transplanted.  Reserve enough
    # for roughly two staged copies plus fixed headroom.  This is
    # intentionally conservative; a false refusal is preferable to filling the
    # volume midway through a 19-hour conversion.
    multiplier = 2.25 if plan.tag_mode == "standard" else 1.35
    required = int(estimate * multiplier) + DISK_HEADROOM_BYTES
    free = shutil.disk_usage(staging_parent).free
    if free < required:
        raise RepairError(
            f"insufficient free space in {staging_parent}: {human_size(free)} free, "
            f"need approximately {human_size(required)}"
        )


