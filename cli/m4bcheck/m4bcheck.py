def user_tags(tags: Mapping[str, str]) -> dict[str, str]:
    excluded = {key.casefold() for key in CONTAINER_TAG_KEYS}
    return {key: value for key, value in tags.items() if key.casefold() not in excluded}


def casefold_tag_map(tags: Mapping[str, str]) -> dict[str, tuple[str, str]]:
    folded: dict[str, tuple[str, str]] = {}
    for key, value in tags.items():
        folded[key.casefold()] = (key, value)
    return folded


def compare_tags(
    source: Mapping[str, str],
    output: Mapping[str, str],
) -> tuple[list[tuple[str, str]], list[tuple[str, str, str]]]:
    """Return (missing, mismatched) source user tags.

    Comparison is case-insensitive for key spelling but exact for values.  An
    unreadable output probe never reaches this function; ProbeError is a
    distinct state rather than being interpreted as an empty tag set.
    """

    source_user = user_tags(source)
    output_user = user_tags(output)
    output_folded = casefold_tag_map(output_user)
    missing: list[tuple[str, str]] = []
    mismatched: list[tuple[str, str, str]] = []

    for key, value in source_user.items():
        found = output_folded.get(key.casefold())
        if found is None:
            missing.append((key, value))
        elif found[1] != value:
            mismatched.append((key, value, found[1]))
    return missing, mismatched


def is_standard_tag(key: str) -> bool:
    return key.casefold() in STANDARD_TAG_KEYS


def ffmetadata_escape(text: str) -> str:
    output: list[str] = []
    for char in text:
        if char in "\\=;#":
            output.append("\\" + char)
        elif char == "\n":
            output.append("\\\n")
        elif char == "\r":
            # Preserve CR explicitly rather than letting it terminate a line.
            output.append("\\\r")
        else:
            output.append(char)
    return "".join(output)


def write_metadata_sidecar(path: Path, tags: Iterable[tuple[str, str]]) -> None:
    pairs = list(tags)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(";FFMETADATA1\n")
        for key, value in pairs:
            handle.write(f"{ffmetadata_escape(key)}={ffmetadata_escape(value)}\n")


def atomicparsley_safe_tag(key: str, value: str) -> bool:
    # AtomicParsley accepts quotes, spaces, Unicode, and '=' as ordinary argv
    # content.  Embedded NUL cannot exist in an argv element, and multiline
    # values have historically been fragile across metadata tools, so those
    # remain in the ffmetadata sidecar instead of being guessed at.
    forbidden = ("\x00", "\n", "\r")
    return not any(token in key or token in value for token in forbidden)


def restore_freeform_tags(
    atomicparsley: str,
    target: Path,
    tags: Sequence[tuple[str, str]],
) -> subprocess.CompletedProcess[str]:
    if not tags:
        return subprocess.CompletedProcess([atomicparsley], 0, "", "")

    args: list[str] = [atomicparsley, str(target), "--overWrite"]
    for key, value in tags:
        args += [
            "--rDNSatom",
            value,
            f"name={key}",
            "domain=com.apple.iTunes",
        ]
    # One invocation only: --overWrite can rewrite the entire large MP4.
    return run_capture(args)


