def ffmpeg_has_component(kind: str, component: str) -> bool:
    """Check ffmpeg decoders/encoders without piping through grep.

    Capturing the entire listing avoids the pipefail/SIGPIPE false-negative that
    occurs when grep -q exits after the first match while ffmpeg is still
    writing.
    """

    switch = "-decoders" if kind == "decoder" else "-encoders"
    result = run_capture(["ffmpeg", "-hide_banner", switch])
    if result.returncode != 0:
        return False
    pattern = re.compile(rf"(?<![A-Za-z0-9_]){re.escape(component)}(?![A-Za-z0-9_])")
    return bool(pattern.search(result.stdout + "\n" + result.stderr))


