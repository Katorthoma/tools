# Diagnosis and planning


def looks_like_xhe(profile: str, codec: str) -> bool:
    text = f"{profile} {codec}".casefold()
    return "xhe" in text or "xhe-aac" in text or "usac" in text


def diagnose(probe: ProbeResult, decoder: DecoderResult) -> Diagnosis:
    notes: list[str] = []
    flags: list[str] = []
    blockers: list[str] = []

    if decoder.kind == DecoderKind.NONE:
        notes.append("no available decoder can read the audio stream from position zero")
        return Diagnosis(DiagnosisState.BROKEN, tuple(notes), decoder)

    needs_encode = False
    needs_remux = False

    if looks_like_xhe(probe.profile, probe.codec):
        needs_encode = True
        notes.append("xHE-AAC / USAC audio requires re-encoding to AAC-LC for browser-safe seeking")

    if decoder.kind == DecoderKind.AAC_AT:
        needs_encode = True
        notes.append("ffmpeg native decoder failed; AudioToolbox aac_at is required for input decoding")

    atom_scan = probe.atom_scan
    if atom_scan.fragmented:
        flag = "fragmented MP4 detected (moof present); generic faststart repair is not assumed safe"
        flags.append(flag)
        notes.append(flag)

    if atom_scan.error is not None:
        flag = f"could not trust MP4 atom-order scan: {atom_scan.error}"
        flags.append(flag)
        notes.append(flag)
    elif atom_scan.faststart is False:
        needs_remux = True
        notes.append("moov atom follows mdat (not faststart)")

    if probe.format_duration is None:
        flag = "container duration is unavailable; stream/container duration comparison was skipped"
        flags.append(flag)
        notes.append(flag)
    else:
        delta = abs(probe.audio_duration - probe.format_duration)
        if delta > DURATION_MISMATCH_TOLERANCE:
            needs_remux = True
            notes.append(f"audio stream and container durations differ by {delta:.3f}s")

    if not probe.chapters:
        flag = "no chapter metadata (playable, but not claimed healthy)"
        flags.append(flag)
        notes.append(flag)
    else:
        last_end = probe.chapters[-1].end
        if last_end > probe.audio_duration + CHAPTER_END_TOLERANCE:
            flag = (
                f"last chapter ends {last_end - probe.audio_duration:.3f}s past the audio stream; "
                "generic remux/encode would preserve the bad timestamp"
            )
            flags.append(flag)
            notes.append(flag)
            blockers.append(flag)

        previous_start = -1.0
        for index, chapter in enumerate(probe.chapters, start=1):
            if chapter.start < 0 or chapter.end < chapter.start:
                flag = f"chapter {index} has an invalid start/end range"
                flags.append(flag)
                notes.append(flag)
                blockers.append(flag)
            if chapter.start + CHAPTER_TIME_TOLERANCE < previous_start:
                flag = f"chapter {index} starts before the preceding chapter"
                flags.append(flag)
                notes.append(flag)
                blockers.append(flag)
            previous_start = chapter.start

    # Fragmentation makes a container-only +faststart remediation ambiguous.
    # A required audio re-encode is still allowed because the new output is a
    # fresh, non-fragmented M4B and must pass the post-write atom verification.
    if atom_scan.fragmented and needs_remux and not needs_encode:
        blocker = "container-only automatic repair is disabled for fragmented MP4"
        flags.append(blocker)
        notes.append(blocker)
        blockers.append(blocker)

    if blockers:
        return Diagnosis(
            DiagnosisState.FLAGGED,
            tuple(notes),
            decoder,
            tuple(flags),
            tuple(blockers),
        )
    if needs_encode:
        return Diagnosis(DiagnosisState.ENCODE, tuple(notes), decoder, tuple(flags))
    if needs_remux:
        return Diagnosis(DiagnosisState.REMUX, tuple(notes), decoder, tuple(flags))
    if flags:
        return Diagnosis(DiagnosisState.FLAGGED, tuple(notes), decoder, tuple(flags))
    return Diagnosis(DiagnosisState.HEALTHY, tuple(notes), decoder)


def parse_bitrate_to_bps(rate: str) -> int:
    match = re.fullmatch(r"\s*(\d+(?:\.\d+)?)\s*([kKmM]?)\s*", rate)
    if not match:
        raise argparse.ArgumentTypeError(
            "bitrate must be a number optionally followed by k or M (for example 96k)"
        )
    number = float(match.group(1))
    suffix = match.group(2).lower()
    multiplier = 1
    if suffix == "k":
        multiplier = 1000
    elif suffix == "m":
        multiplier = 1_000_000
    bps = int(number * multiplier)
    if bps <= 0:
        raise argparse.ArgumentTypeError("bitrate must be greater than zero")
    return bps


def estimate_output_size(probe: ProbeResult, action: RepairAction, bitrate: str) -> int:
    if action == RepairAction.REMUX:
        return probe.size
    bps = parse_bitrate_to_bps(bitrate)
    estimate = int((bps / 8.0) * probe.audio_duration * 1.03)
    if probe.has_cover:
        estimate += 2 * 1024 * 1024
    return max(estimate, 1)


def default_suffix(plan_action: RepairAction, bitrate: str, mono: bool, channels: int) -> str:
    if plan_action == RepairAction.REMUX:
        return " [Fixed remux]"
    if mono or channels == 1:
        channel_label = "mono"
    elif channels == 2:
        channel_label = "stereo"
    else:
        channel_label = f"{channels}ch"
    return f" [Fixed {bitrate} {channel_label}]"



