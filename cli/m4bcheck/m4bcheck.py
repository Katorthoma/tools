@dataclass(frozen=True)
class StereoAnalysis:
    """Distributed advisory stereo analysis.

    This is intentionally conservative.  A mono recommendation is offered only
    when every planned window decoded successfully and every measured L-R delta
    is below the threshold.  Sampling can never prove that an unsampled moment
    contains no stereo content, so the result remains advisory and only an
    explicit user choice can downmix.
    """

    samples: tuple[StereoSample, ...]
    error: str | None = None

    @property
    def successful_samples(self) -> tuple[StereoSample, ...]:
        return tuple(sample for sample in self.samples if sample.mean_delta_db is not None)

    @property
    def failed_samples(self) -> tuple[StereoSample, ...]:
        return tuple(sample for sample in self.samples if sample.mean_delta_db is None)

    @property
    def worst_sample(self) -> StereoSample | None:
        successful = self.successful_samples
        if not successful:
            return None
        # The least-negative L-R delta is the strongest evidence of stereo.
        return max(successful, key=lambda sample: sample.mean_delta_db if sample.mean_delta_db is not None else float('-inf'))

    @property
    def advisory_mono(self) -> bool:
        return (
            bool(self.samples)
            and not self.failed_samples
            and all(
                sample.mean_delta_db is not None
                and sample.mean_delta_db < MONO_ADVISORY_THRESHOLD_DB
                for sample in self.samples
            )
        )

    @property
    def stereo_detected(self) -> bool:
        return any(sample.stereo_detected for sample in self.samples)


