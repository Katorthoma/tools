def decoder_label(decoder: DecoderResult) -> str:
    if decoder.kind == DecoderKind.NATIVE:
        return "ffmpeg native"
    if decoder.kind == DecoderKind.AAC_AT:
        return "AudioToolbox (aac_at)"
    return "none available"


def _format_delta(value: float) -> str:
    return "-inf" if math.isinf(value) else f"{value:.1f}"


def format_stereo(stereo: StereoAnalysis) -> str | None:
    successful = stereo.successful_samples
    if not successful:
        return None

    worst = stereo.worst_sample
    assert worst is not None and worst.mean_delta_db is not None
    analyzed = len(successful)
    planned = len(stereo.samples)
    worst_text = _format_delta(worst.mean_delta_db)

    if stereo.stereo_detected:
        verdict = f"stereo difference detected; strongest {worst_text} dB at {worst.label}"
    elif stereo.failed_samples:
        verdict = (
            f"{len(stereo.failed_samples)} window(s) unavailable; mono recommendation suppressed"
        )
    else:
        verdict = (
            f"all sampled windows appear effectively mono; worst {worst_text} dB at {worst.label}"
        )
    return f"{analyzed}/{planned} distributed windows; {verdict} (advisory only)"


def print_scan_item(scan: ScanItem) -> None:
    print(style(scan.input_item.path.name, ANSI_BOLD))
    if scan.error:
        print(style(f"  ERROR      {scan.error}", ANSI_RED, stream=sys.stderr))
        return

    assert scan.probe is not None
    assert scan.decoder is not None
    assert scan.diagnosis is not None
    probe = scan.probe
    profile = probe.profile or "?"
    sample_rate = f"{probe.sample_rate} Hz" if probe.sample_rate is not None else "? Hz"
    channels = "mono" if probe.channels == 1 else "stereo" if probe.channels == 2 else f"{probe.channels} ch"
    print(f"  {report_label('audio')} {probe.codec} / {profile}, {channels}, {sample_rate}")
    print(f"  {report_label('length')} {human_time(probe.audio_duration)}   size {human_size(probe.size)}")
    print(f"  {report_label('chapters')} {len(probe.chapters)}")
    print(f"  {report_label('decoder')} {decoder_label(scan.decoder)}")

    atom = probe.atom_scan
    if atom.fragmented:
        atom_label = "fragmented"
    elif atom.faststart is True:
        atom_label = "faststart"
    elif atom.faststart is False:
        atom_label = "moov after mdat"
    else:
        atom_label = f"unknown ({atom.error})"
    print(f"  {report_label('container')} {atom_label}")

    if scan.stereo is not None:
        stereo_text = format_stereo(scan.stereo)
        if stereo_text:
            print(f"  {report_label('stereo')} {stereo_text}")
        elif scan.stereo.error:
            print(f"  {report_label('stereo')} unavailable: {scan.stereo.error}")

    for note in scan.diagnosis.notes:
        print(style(f"  !          {note}", ANSI_YELLOW))

    state = scan.diagnosis.state
    if state == DiagnosisState.HEALTHY:
        result = style("looks healthy", ANSI_GREEN)
    elif state == DiagnosisState.FLAGGED:
        result = style("flagged for manual attention; no automatic repair planned", ANSI_YELLOW)
    elif state == DiagnosisState.REMUX:
        suffix = "; also flagged" if scan.diagnosis.has_flags else ""
        result = style(f"needs lossless remux{suffix}", ANSI_YELLOW)
    elif state == DiagnosisState.ENCODE:
        suffix = "; also flagged" if scan.diagnosis.has_flags else ""
        result = style(f"needs AAC re-encode{suffix}", ANSI_YELLOW)
    elif state == DiagnosisState.BROKEN:
        result = style("no available decoder can repair this audio", ANSI_RED)
    else:
        result = style("scan error", ANSI_RED)
    print(f"  {report_label('result')} {result}")

def build_plan(
    scan: ScanItem,
    args: argparse.Namespace,
    outdir: Path | None,
    *,
    mono_override: bool | None = None,
) -> RepairPlan | None:
    if scan.error or scan.probe is None or scan.decoder is None or scan.diagnosis is None:
        return None
    if not scan.diagnosis.repairable:
        return None

    action = RepairAction.REMUX if scan.diagnosis.state == DiagnosisState.REMUX else RepairAction.ENCODE
    if args.force_encode and action == RepairAction.REMUX:
        action = RepairAction.ENCODE

    # Mono is never inferred from the advisory distributed stereo analysis.  It is only an
    # explicit user request.  Keep bitrate choice local to this file/plan so a
    # mono decision can never leak into a different batch item.
    requested_mono = args.mono if mono_override is None else mono_override
    mono = bool(requested_mono and action == RepairAction.ENCODE)
    bitrate = args.bitrate or (DEFAULT_MONO_BITRATE if mono else DEFAULT_BITRATE)

    suffix = args.suffix
    if suffix is None:
        suffix = default_suffix(action, bitrate, mono, scan.probe.channels)

    if args.replace:
        destination = scan.probe.path
    elif outdir is None:
        destination = scan.probe.path.parent / f"{scan.probe.path.stem}{suffix}.m4b"
    else:
        destination = outdir / scan.input_item.relative_path.parent / f"{scan.probe.path.stem}{suffix}.m4b"

    if not args.replace:
        try:
            if destination.resolve(strict=False) == scan.probe.path.resolve(strict=True):
                raise M4BCheckError(
                    f"output path would equal source for {scan.probe.path}; use --replace for intentional replacement"
                )
        except OSError as exc:
            raise M4BCheckError(f"could not resolve output path {destination}: {exc}") from exc

    return RepairPlan(
        source=scan.probe.path,
        destination=destination,
        action=action,
        input_decoder=scan.decoder.kind,
        output_encoder=args.encoder,
        bitrate=bitrate,
        mono=mono,
        tag_mode=args.tags,
        keep_cover=not args.no_cover,
        replace=args.replace,
        expected=scan.probe,
    )


def preflight_destination_collisions(plans: Sequence[RepairPlan]) -> None:
    seen: dict[Path, Path] = {}
    for plan in plans:
        if plan.replace:
            continue
        key = plan.destination.resolve(strict=False)
        previous = seen.get(key)
        if previous is not None and previous != plan.source:
            raise M4BCheckError(
                f"two inputs map to the same output {plan.destination}: {previous} and {plan.source}"
            )
        seen[key] = plan.source


def _chapters_equivalent(
    source: ProbeResult,
    candidate: ProbeResult,
    *,
    tolerance: float = CHAPTER_TIME_TOLERANCE,
) -> bool:
    if len(source.chapters) != len(candidate.chapters):
        return False
    return all(
        left.title == right.title
        and abs(left.start - right.start) <= tolerance
        and abs(left.end - right.end) <= tolerance
        for left, right in zip(source.chapters, candidate.chapters)
    )


def _looks_like_verified_fixed_sibling(
    plan: RepairPlan,
    candidate_scan: ScanItem,
) -> bool:
    """Return true only when a scanned ``[Fixed ...]`` sibling matches source.

    A batch plan is initially built using the conservative channel-preserving
    choice.  That means an existing ``[Fixed 64k mono]`` file cannot equal the
    initial ``[Fixed 96k stereo]`` destination even though it may already be a
    valid repair selected interactively on an earlier run.

    We therefore recognize a sibling by *content invariants*, not by bitrate or
    channel suffix alone: healthy/faststart output, matching duration and exact
    chapter records, and the same normalized MP4 user-data capsule.  For an
    encode repair the sibling must also be AAC-LC.  This is intentionally much
    stricter than merely finding a similarly named file.
    """

    if candidate_scan.error is not None or candidate_scan.probe is None:
        return False
    if candidate_scan.diagnosis is None or candidate_scan.diagnosis.state not in {
        DiagnosisState.HEALTHY,
        DiagnosisState.FLAGGED,
    }:
        return False

    source = plan.expected
    candidate = candidate_scan.probe
    if candidate.path == source.path or candidate.path.parent != source.path.parent:
        return False

    prefix = f"{source.path.stem} [Fixed "
    if not (candidate.path.name.startswith(prefix) and candidate.path.name.endswith("].m4b")):
        return False

    if candidate.atom_scan.faststart is not True or candidate.atom_scan.fragmented:
        return False
    if abs(candidate.audio_duration - source.audio_duration) > VERIFY_DURATION_TOLERANCE:
        return False
    if not _chapters_equivalent(source, candidate):
        return False

    if plan.action == RepairAction.ENCODE:
        if candidate.codec.lower() != "aac" or candidate.profile.upper() != "LC":
            return False
        # A prior explicit mono choice may legitimately reduce stereo to mono.
        # Any other channel-layout change is not a repair we can safely infer.
        allowed_channels = {source.channels}
        if source.channels == 2:
            allowed_channels.add(1)
        if candidate.channels not in allowed_channels:
            return False
    elif plan.action == RepairAction.REMUX:
        if candidate.codec != source.codec or candidate.profile != source.profile:
            return False

    try:
        source_capsule = metadata_capsule(source.path, keep_cover=plan.keep_cover)
        candidate_capsule = metadata_capsule(candidate.path, keep_cover=plan.keep_cover)
    except M4BCheckError:
        return False
    return source_capsule.normalized_udta == candidate_capsule.normalized_udta


def reconcile_scanned_existing_outputs(
    plans: Sequence[RepairPlan],
    scans: Sequence[ScanItem],
) -> tuple[list[RepairPlan], list[tuple[RepairPlan, ScanItem]]]:
    """Omit plans already satisfied by a healthy scanned repair sibling.

    Exact planned destinations are preferred.  We also recognize a default
    ``[Fixed ...]`` sibling whose content invariants prove it represents the same
    source.  This matters because the initial batch plan preserves channels,
    while a previous interactive run may have explicitly chosen 64k mono.

    Only files included in the current scan are eligible.  Direct single-file
    runs therefore retain the conservative existing-output collision behavior.
    """

    scanned_by_path: dict[Path, ScanItem] = {}
    scans_by_parent: dict[Path, list[ScanItem]] = {}
    for scan in scans:
        try:
            key = scan.input_item.path.resolve(strict=True)
        except OSError:
            continue
        scanned_by_path[key] = scan
        scans_by_parent.setdefault(key.parent, []).append(scan)

    active: list[RepairPlan] = []
    satisfied: list[tuple[RepairPlan, ScanItem]] = []
    for plan in plans:
        if plan.replace:
            active.append(plan)
            continue

        existing_scan: ScanItem | None = None
        if plan.destination.exists():
            try:
                destination_key = plan.destination.resolve(strict=True)
            except OSError:
                destination_key = None
            if destination_key is not None:
                exact_scan = scanned_by_path.get(destination_key)
                if exact_scan is not None and _looks_like_verified_fixed_sibling(plan, exact_scan):
                    existing_scan = exact_scan

        if existing_scan is None:
            try:
                source_parent = plan.source.resolve(strict=True).parent
            except OSError:
                source_parent = plan.source.parent.resolve(strict=False)
            for candidate_scan in scans_by_parent.get(source_parent, []):
                if _looks_like_verified_fixed_sibling(plan, candidate_scan):
                    existing_scan = candidate_scan
                    break

        if existing_scan is not None:
            satisfied.append((plan, existing_scan))
        else:
            active.append(plan)

    return active, satisfied


def _promotion_plan_for_candidate(plan: RepairPlan, candidate_scan: ScanItem) -> RepairPlan:
    """Build a verification plan that describes the already-created candidate.

    The candidate may be an explicitly selected mono repair even though the source
    was stereo.  Verification must therefore expect the candidate's intentional
    channel count rather than the conservative default plan built during scanning.
    """

    if candidate_scan.probe is None:
        raise M4BCheckError("fixed candidate has no probe result")
    candidate = candidate_scan.probe
    mono = (
        plan.action == RepairAction.ENCODE
        and plan.expected.channels == 2
        and candidate.channels == 1
    )
    bitrate = (
        f"{max(1, round(candidate.bit_rate / 1000))}k"
        if candidate.bit_rate is not None
        else (DEFAULT_MONO_BITRATE if mono else DEFAULT_BITRATE)
    )
    return replace(
        plan,
        destination=plan.source,
        bitrate=bitrate,
        mono=mono,
        tag_mode="standard",
        keep_cover=True,
        replace=True,
    )


def find_fixed_promotions(
    plans: Sequence[RepairPlan],
    scans: Sequence[ScanItem],
) -> tuple[list[FixedPromotion], list[tuple[RepairPlan, tuple[ScanItem, ...]]], list[RepairPlan]]:
    """Find strict existing ``[Fixed ...]`` siblings for --replace-fixed.

    Returns (unambiguous promotions, ambiguous matches, unmatched repair plans).
    Only candidates that pass the same structural/content invariants used by the
    normal already-repaired reconciliation are considered.  Multiple valid fixed
    siblings are deliberately ambiguous; choosing one implicitly would be a data
    policy decision rather than a safety operation.
    """

    scans_by_parent: dict[Path, list[ScanItem]] = {}
    for scan in scans:
        try:
            parent = scan.input_item.path.resolve(strict=True).parent
        except OSError:
            continue
        scans_by_parent.setdefault(parent, []).append(scan)

    promotions: list[FixedPromotion] = []
    ambiguous: list[tuple[RepairPlan, tuple[ScanItem, ...]]] = []
    unmatched: list[RepairPlan] = []

    for plan in plans:
        try:
            parent = plan.source.resolve(strict=True).parent
        except OSError:
            parent = plan.source.parent.resolve(strict=False)
        matches = tuple(
            candidate
            for candidate in scans_by_parent.get(parent, [])
            if _looks_like_verified_fixed_sibling(plan, candidate)
        )
        if len(matches) == 1:
            promotions.append(
                FixedPromotion(
                    source_plan=plan,
                    candidate_scan=matches[0],
                    verification_plan=_promotion_plan_for_candidate(plan, matches[0]),
                )
            )
        elif len(matches) > 1:
            ambiguous.append((plan, matches))
        else:
            unmatched.append(plan)

    return promotions, ambiguous, unmatched


def _promotion_sidecars(candidate: Path) -> tuple[Path, ...]:
    stem = candidate.with_suffix("")
    possible = (Path(str(stem) + ".metadata.txt"), Path(str(stem) + ".jpg"))
    return tuple(path for path in possible if path.exists())


def commit_existing_fixed(
    promotion: FixedPromotion,
    *,
    progress: ProgressReporter | None = None,
) -> str:
    """Atomically promote a verified fixed sibling while retaining the original.

    The original remains live until a no-clobber backup has been created.  The
    candidate and source are siblings, so ``os.replace`` is a same-filesystem
    atomic rename.  We currently refuse fixed outputs with sidecars because
    silently renaming only the audio would orphan those preservation artifacts.
    """

    source = promotion.source_plan.source
    candidate_probe = promotion.candidate_scan.probe
    if candidate_probe is None:
        raise TransactionError("fixed candidate probe disappeared before commit")
    candidate = candidate_probe.path
    backup = source.with_name(source.name + ".bak")

    if backup.exists():
        raise TransactionError(f"backup already exists; refusing replacement: {backup}")
    sidecars = _promotion_sidecars(candidate)
    if sidecars:
        raise TransactionError(
            "--replace-fixed currently refuses candidates with sidecars: "
            + ", ".join(str(path) for path in sidecars)
        )
    if not candidate.exists():
        raise TransactionError(f"fixed candidate disappeared before commit: {candidate}")

    backup_method = create_backup_without_removing_source(source, backup, progress=progress)
    try:
        os.replace(candidate, source)
    except Exception as exc:
        try:
            backup.unlink()
        except OSError:
            pass
        raise TransactionError(
            f"could not promote fixed sibling; original remains in place: {exc}"
        ) from exc
    return backup_method


def run_replace_fixed(
    plans: Sequence[RepairPlan],
    scans: Sequence[ScanItem],
    args: argparse.Namespace,
) -> int:
    promotions, ambiguous, unmatched = find_fixed_promotions(plans, scans)

    print()
    print(f"{style('Existing verified fixes:', ANSI_CYAN)} {len(promotions)}")
    for promotion in promotions:
        assert promotion.candidate_scan.probe is not None
        print(
            f"  {style('✓', ANSI_GREEN)} {promotion.source_plan.source.name} <- "
            f"{promotion.candidate_scan.probe.path.name}"
        )

    if ambiguous:
        print(f"{style('Ambiguous fixed siblings:', ANSI_YELLOW)} {len(ambiguous)}")
        for plan, candidates in ambiguous:
            print(f"  {plan.source.name}")
            for candidate in candidates:
                if candidate.probe is not None:
                    print(f"    - {candidate.probe.path.name}")
        print("  Refusing to choose between multiple valid fixed outputs.")

    print(f"{style('Repairable without an existing fix:', ANSI_BLUE)} {len(unmatched)}")
    if unmatched:
        print("  These files are not encoded by --replace-fixed.")

    if args.dry_run:
        print("\nDry run: no files replaced.")
        return summarize_exit(scans, [])

    if ambiguous:
        print(style("\nNo replacements performed because one or more sources are ambiguous.", ANSI_RED, stream=sys.stderr), file=sys.stderr)
        return 1

    if not promotions:
        print("\nNo existing verified [Fixed ...] siblings are eligible for replacement.")
        return summarize_exit(scans, [])

    blocked = [
        promotion.source_plan.source.with_name(promotion.source_plan.source.name + ".bak")
        for promotion in promotions
        if promotion.source_plan.source.with_name(promotion.source_plan.source.name + ".bak").exists()
    ]
    if blocked:
        print("Existing backup file(s) block --replace-fixed:", file=sys.stderr)
        for backup in blocked:
            print(f"  {backup}", file=sys.stderr)
        print("Refusing to overwrite a prior backup.", file=sys.stderr)
        return 1

    if not args.yes:
        if not sys.stdin.isatty():
            print(style("error: not interactive and --yes was not given", ANSI_RED, stream=sys.stderr), file=sys.stderr)
            return 1
        reply = input(
            style(
                f"\nPromote {len(promotions)} existing fixed file(s) over their originals, keeping .bak? [y/N] ",
                ANSI_BOLD,
            )
        ).strip().casefold()
        if reply not in {"y", "yes"}:
            print("Cancelled.")
            return summarize_exit(scans, [])

    failures = 0
    for index, promotion in enumerate(promotions, start=1):
        candidate_probe = promotion.candidate_scan.probe
        assert candidate_probe is not None
        print(f"\n[{index}/{len(promotions)}] {promotion.source_plan.source.name}")
        print(f"  verifying existing fix -> {candidate_probe.path.name}")
        progress = ProgressReporter()
        verification = verify_output(
            promotion.verification_plan,
            candidate_probe.path,
            expect_embedded_cover=promotion.source_plan.expected.has_cover,
            progress=progress,
        )
        progress.finish_update()
        if not verification.ok:
            failures += 1
            print(style("  FAILED verification; original left untouched", ANSI_RED, stream=sys.stderr), file=sys.stderr)
            for failure in verification.failures:
                print(style(f"    ✗ {failure}", ANSI_RED, stream=sys.stderr), file=sys.stderr)
            continue

        try:
            commit_existing_fixed(promotion, progress=progress)
        except TransactionError as exc:
            failures += 1
            print(style(f"  FAILED commit: {exc}", ANSI_RED, stream=sys.stderr), file=sys.stderr)
            continue

        print(style(f"  done: fixed sibling promoted; backup at {promotion.source_plan.source.name}.bak", ANSI_GREEN))
        for check in verification.checks:
            print(style(f"    ✓ {check}", ANSI_GREEN))

    if failures:
        print(style(f"\nFinished with {failures} replacement failure(s).", ANSI_RED, stream=sys.stderr), file=sys.stderr)
        return 1

    print(style("\nExisting fixed outputs promoted successfully.", ANSI_GREEN))
    if unmatched:
        print(f"{len(unmatched)} repairable file(s) remain; run m4bcheck --replace to convert them when ready.")
    return 0


def advisory_mono_candidates(
    scans: Sequence[ScanItem],
    plans: Sequence[RepairPlan],
) -> list[ScanItem]:
    """Return encode plans whose distributed samples are dual-mono-like.

    The analysis remains advisory.  Every planned window must decode and remain
    below the stereo threshold before the convenient explicit mono choice is
    offered.
    """

    plan_sources = {plan.source for plan in plans if plan.action == RepairAction.ENCODE and not plan.mono}
    return [
        scan
        for scan in scans
        if scan.probe is not None
        and scan.probe.path in plan_sources
        and scan.probe.channels == 2
        and scan.stereo is not None
        and scan.stereo.advisory_mono
    ]


def plans_with_advisory_mono(
    plans: Sequence[RepairPlan],
    candidates: Sequence[ScanItem],
    args: argparse.Namespace,
    outdir: Path | None,
) -> list[RepairPlan]:
    candidate_by_source = {scan.probe.path: scan for scan in candidates if scan.probe is not None}
    revised: list[RepairPlan] = []
    for plan in plans:
        scan = candidate_by_source.get(plan.source)
        if scan is None:
            revised.append(plan)
            continue
        replacement_plan = build_plan(scan, args, outdir, mono_override=True)
        if replacement_plan is None:
            raise M4BCheckError(f"could not build mono repair plan for {plan.source}")
        revised.append(replacement_plan)
    preflight_destination_collisions(revised)
    return revised


def print_interactive_encoding_choices(
    plans: Sequence[RepairPlan],
    mono_plans: Sequence[RepairPlan],
    candidates: Sequence[ScanItem],
) -> None:
    stereo_total = sum(estimate_output_size(plan.expected, plan.action, plan.bitrate) for plan in plans)
    mono_total = sum(estimate_output_size(plan.expected, plan.action, plan.bitrate) for plan in mono_plans)

    print()
    print(style("Encoding choices", ANSI_BOLD, ANSI_CYAN))
    if len(plans) == 1 and len(candidates) == 1:
        stereo_plan = plans[0]
        mono_plan = mono_plans[0]
        stereo_label = (
            f"{stereo_plan.bitrate} "
            f"{'mono' if stereo_plan.expected.channels == 1 else 'stereo'}"
        )
        mono_label = f"{mono_plan.bitrate} mono"
        analysis = candidates[0].stereo
        advisory_text = ""
        if analysis is not None and analysis.worst_sample is not None:
            worst = analysis.worst_sample
            assert worst.mean_delta_db is not None
            advisory_text = (
                f"; {len(analysis.successful_samples)}/{len(analysis.samples)} sampled windows "
                f"below {_format_delta(MONO_ADVISORY_THRESHOLD_DB)} dB "
                f"(worst {_format_delta(worst.mean_delta_db)} dB at {worst.label})"
            )
        print(
            f"  {style('[s]', ANSI_CYAN)} {stereo_label:<13} "
            f"~{human_size(stereo_total):<10} preserve channels"
        )
        print(
            f"  {style('[m]', ANSI_CYAN)} {mono_label:<13} "
            f"~{human_size(mono_total):<10} explicit downmix"
            + advisory_text
        )
    else:
        print(
            f"  {style('[s]', ANSI_CYAN)} preserve configured channels for all repairable files "
            f"(~{human_size(stereo_total)})"
        )
        candidate_sources = {
            candidate.probe.path
            for candidate in candidates
            if candidate.probe is not None
        }
        candidate_mono_plans = [
            plan for plan in mono_plans if plan.source in candidate_sources and plan.mono
        ]
        if candidate_mono_plans:
            mono_bitrates = sorted({plan.bitrate for plan in candidate_mono_plans})
            if len(mono_bitrates) == 1:
                mono_rate_text = f"to {mono_bitrates[0]} mono "
            else:
                mono_rate_text = (
                    "using per-file mono bitrates "
                    f"({', '.join(mono_bitrates)}) "
                )
        else:
            # This should be impossible when the caller supplies advisory candidates,
            # but display code must never be allowed to crash the repair workflow.
            mono_rate_text = "using per-file mono settings "
        print(
            f"  {style('[m]', ANSI_CYAN)} downmix {len(candidates)} advisory-mono candidate(s) "
            f"{mono_rate_text}"
            f"(~{human_size(mono_total)} total)"
        )
    print(f"  {style('[N]', ANSI_CYAN)} cancel")


def scan_inputs(items: Sequence[InputItem], *, quick: bool, aac_at_available: bool) -> list[ScanItem]:
    scans: list[ScanItem] = []
    for item in items:
        scan = ScanItem(item)
        try:
            probe = probe_file(item.path)
            decoder = detect_decoder(probe, aac_at_available=aac_at_available)
            diagnosis = diagnose(probe, decoder)
            stereo: StereoAnalysis | None = None
            if not quick and probe.channels == 2 and decoder.kind != DecoderKind.NONE:
                stereo = stereo_delta(probe, decoder.kind)
            scan.probe = probe
            scan.decoder = decoder
            scan.diagnosis = diagnosis
            scan.stereo = stereo
        except M4BCheckError as exc:
            scan.error = str(exc)
        except OSError as exc:
            scan.error = f"filesystem error: {exc}"
        scans.append(scan)
    return scans


def summarize_exit(scans: Sequence[ScanItem], outcomes: Sequence[RepairOutcome]) -> int:
    if any(not outcome.success for outcome in outcomes):
        return 1
    if any(scan.error for scan in scans):
        return 1
    if any(scan.diagnosis and scan.diagnosis.state == DiagnosisState.BROKEN for scan in scans):
        return 2
    if any(scan.diagnosis and scan.diagnosis.has_flags for scan in scans):
        return 3
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    validate_args(parser, args)

    require_program("ffmpeg")
    require_program("ffprobe")

    aac_at_available = ffmpeg_has_component("decoder", "aac_at")
    if args.encoder == "aac_at" and not ffmpeg_has_component("encoder", "aac_at"):
        parser.error("--encoder aac_at requested, but this ffmpeg build has no aac_at encoder")

    atomicparsley = find_atomicparsley()
    outdir: Path | None = None
    if args.outdir is not None:
        outdir = args.outdir.expanduser().resolve(strict=False)

    items = collect_inputs(args.targets, recursive=not args.flat)
    if args.replace_fixed:
        items = include_fixed_siblings_for_replace_fixed(items)
    if not items:
        print("error: no .m4b or .m4a files found", file=sys.stderr)
        return 1

    print(style(f"m4bcheck v{VERSION}", ANSI_BOLD, ANSI_CYAN))
    print(style(f"Scanning {len(items)} file(s)...", ANSI_BOLD, ANSI_CYAN) + "\n")
    scans = scan_inputs(items, quick=args.quick, aac_at_available=aac_at_available)
    for scan in scans:
        print_scan_item(scan)
        print()

    plans: list[RepairPlan] = []
    for scan in scans:
        try:
            plan = build_plan(scan, args, outdir)
        except M4BCheckError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
        if plan is not None:
            plans.append(plan)

    try:
        preflight_destination_collisions(plans)
    except M4BCheckError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.replace_fixed:
        return run_replace_fixed(plans, scans, args)

    plans, existing_healthy_outputs = reconcile_scanned_existing_outputs(plans, scans)

    print(f"{style('Repairable:', ANSI_CYAN)} {len(plans)}")
    if existing_healthy_outputs:
        print(f"{style('Already repaired:', ANSI_GREEN)} {len(existing_healthy_outputs)}")
        for plan, existing_scan in existing_healthy_outputs:
            existing_name = (
                existing_scan.probe.path.name
                if existing_scan.probe is not None
                else plan.destination.name
            )
            print(
                f"  {style('✓', ANSI_GREEN)} {plan.source.name} -> "
                f"{existing_name} (existing output scanned healthy)"
            )
    broken_count = sum(
        1
        for scan in scans
        if scan.diagnosis is not None and scan.diagnosis.state == DiagnosisState.BROKEN
    )
    flagged_count = sum(
        1
        for scan in scans
        if scan.diagnosis is not None and scan.diagnosis.has_flags
    )
    error_count = sum(1 for scan in scans if scan.error)
    print(
        f"{style('Flagged/manual:', ANSI_YELLOW)} {flagged_count}   "
        f"{style('Undecodable:', ANSI_RED)} {broken_count}   "
        f"{style('Scan errors:', ANSI_RED)} {error_count}"
    )

    if plans:
        current_total = sum(plan.expected.size for plan in plans)
        estimated_total = sum(estimate_output_size(plan.expected, plan.action, plan.bitrate) for plan in plans)
        print(f"{style('Current repair-set size:', ANSI_BLUE)} {human_size(current_total)}")
        print(f"{style('Estimated output size:', ANSI_BLUE)}   {human_size(estimated_total)}")
        print(
            f"{style('Settings:', ANSI_BLUE)} encoder {args.encoder}, tags {args.tags}, "
            f"{'explicit mono' if args.mono else 'channels preserved'}"
        )
        if args.tags == "standard":
            print(f"{style('Metadata:', ANSI_BLUE)} exact MP4 user-data transplant (Mp3tag-safe)")
            if atomicparsley:
                print(
                    f"{style('AtomicParsley:', ANSI_BLUE)} {style(atomicparsley, ANSI_GREEN)} "
                    "(available; not required for standard mode)"
                )

    if args.dry_run:
        print("\nDry run: no files written.")
        return summarize_exit(scans, [])

    existing_outputs = [plan for plan in plans if not plan.replace and plan.destination.exists()]
    if existing_outputs:
        print("Existing output file(s) block this run:", file=sys.stderr)
        for plan in existing_outputs:
            print(f"  {plan.destination}", file=sys.stderr)
        print("Refusing to skip silently; choose another suffix/outdir or remove the old output.", file=sys.stderr)
        return 1

    existing_backups = [
        plan.source.with_name(plan.source.name + ".bak")
        for plan in plans
        if plan.replace and plan.source.with_name(plan.source.name + ".bak").exists()
    ]
    if existing_backups:
        print("Existing backup file(s) block --replace:", file=sys.stderr)
        for backup in existing_backups:
            print(f"  {backup}", file=sys.stderr)
        print("Refusing to overwrite a prior backup.", file=sys.stderr)
        return 1

    if not plans:
        if broken_count:
            print("\nNo automatic repairs can be performed on the undecodable file(s).")
        elif flagged_count or error_count:
            print("\nNo automatic repairs planned; flagged/error items require attention.")
        else:
            print("\nNothing to do; every file checked out healthy.")
        return summarize_exit(scans, [])

    if not args.yes:
        if not sys.stdin.isatty():
            print(style("error: not interactive and --yes was not given", ANSI_RED, stream=sys.stderr), file=sys.stderr)
            return 1

        candidates = advisory_mono_candidates(scans, plans) if not args.mono else []
        if candidates:
            try:
                mono_plans = plans_with_advisory_mono(plans, candidates, args, outdir)
            except M4BCheckError as exc:
                print(style(f"error: {exc}", ANSI_RED, stream=sys.stderr), file=sys.stderr)
                return 1
            print_interactive_encoding_choices(plans, mono_plans, candidates)
            reply = input(style("Choose repair mode [s/m/N]: ", ANSI_BOLD)).strip().casefold()
            if reply in {"m", "mono"}:
                plans = mono_plans
                print(style("Selected: mono downmix for advisory candidate(s).", ANSI_CYAN))
            elif reply in {"s", "stereo", "p", "preserve", "y", "yes"}:
                print(style("Selected: preserve channels.", ANSI_CYAN))
            else:
                print("Cancelled.")
                return summarize_exit(scans, [])
        else:
            reply = input(style(f"\nRepair {len(plans)} file(s) now? [y/N] ", ANSI_BOLD)).strip().casefold()
            if reply not in {"y", "yes"}:
                print("Cancelled.")
                return summarize_exit(scans, [])

    outcomes: list[RepairOutcome] = []
    for index, plan in enumerate(plans, start=1):
        print(f"\n[{index}/{len(plans)}] {plan.source.name}")
        print(
            f"  {'remuxing' if plan.action == RepairAction.REMUX else 'encoding'} -> "
            f"{plan.destination if not plan.replace else plan.source}"
        )
        progress = ProgressReporter()
        outcome = repair_transaction(plan, atomicparsley=atomicparsley, progress=progress)
        progress.finish_update()
        outcomes.append(outcome)
        if outcome.success:
            assert outcome.destination is not None
            print(style(f"  done: {outcome.message}", ANSI_GREEN))
            if outcome.verification is not None:
                for check in outcome.verification.checks:
                    print(style(f"    ✓ {check}", ANSI_GREEN))
        else:
            print(style(f"  FAILED: {outcome.message}", ANSI_RED, stream=sys.stderr), file=sys.stderr)

    failures = sum(1 for outcome in outcomes if not outcome.success)
    if failures:
        print(style(f"\nFinished with {failures} repair failure(s).", ANSI_RED, stream=sys.stderr), file=sys.stderr)
    else:
        print(style("\nRepairs complete. Rescan the library in Audiobookshelf before testing chapter seeks.", ANSI_GREEN))

    return summarize_exit(scans, outcomes)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        # TemporaryDirectory contexts unwind on KeyboardInterrupt, removing
        # staged outputs.  A verified original is not renamed until commit.
        print("\nInterrupted; staged files were not committed.", file=sys.stderr)
        raise SystemExit(130)
