def is_ignorable_macos_metadata(path: Path) -> bool:
    """Return True for macOS metadata sidecars that only masquerade as media.

    FAT/exFAT/SMB and other non-native filesystems can contain AppleDouble
    companion files named ``._<real-name>``.  A ``._Book.m4b`` is not an M4B;
    it is Finder/resource-fork metadata with the media filename's extension.
    Treating it as an audiobook creates noisy ffprobe errors in folder scans.

    ``__MACOSX`` is the equivalent metadata directory commonly produced by
    Archive Utility.  Neither form is a user media file.
    """

    return path.name.startswith("._") or "__MACOSX" in path.parts


def collect_inputs(targets: Sequence[str], recursive: bool) -> list[InputItem]:
    items: list[InputItem] = []
    seen: set[Path] = set()

    for target_text in targets:
        target = Path(target_text).expanduser()
        try:
            target = target.resolve(strict=True)
        except FileNotFoundError:
            print(f"warning: skipping {target_text!r} (not found)", file=sys.stderr)
            continue

        if target.is_file():
            if is_ignorable_macos_metadata(target):
                print(f"warning: skipping macOS metadata sidecar {target}", file=sys.stderr)
                continue
            if target.suffix.casefold() not in {".m4b", ".m4a"}:
                print(f"warning: skipping {target} (not .m4b/.m4a)", file=sys.stderr)
                continue
            if target not in seen:
                seen.add(target)
                items.append(InputItem(target, Path(target.name), None))
            continue

        if not target.is_dir():
            print(f"warning: skipping {target} (not a regular file or directory)", file=sys.stderr)
            continue

        iterator = target.rglob("*") if recursive else target.glob("*")
        for candidate in iterator:
            try:
                if is_ignorable_macos_metadata(candidate):
                    continue
                if not candidate.is_file() or candidate.suffix.casefold() not in {".m4b", ".m4a"}:
                    continue
                resolved = candidate.resolve(strict=True)
            except OSError:
                continue
            if resolved in seen:
                continue
            seen.add(resolved)
            try:
                relative = resolved.relative_to(target)
            except ValueError:
                relative = Path(resolved.name)
            items.append(InputItem(resolved, relative, target))

    items.sort(key=lambda item: os.fsencode(str(item.path)))
    return items


def include_fixed_siblings_for_replace_fixed(items: Sequence[InputItem]) -> list[InputItem]:
    """Ensure direct-file --replace-fixed runs can see adjacent fixed outputs.

    Directory scans already include these files naturally.  A direct invocation
    such as ``m4bcheck --replace-fixed Book.m4b`` would otherwise scan only the
    source and never discover ``Book [Fixed 64k mono].m4b`` beside it.
    """

    expanded = list(items)
    seen: set[Path] = set()
    for item in expanded:
        try:
            seen.add(item.path.resolve(strict=True))
        except OSError:
            pass

    for item in list(items):
        if " [Fixed " in item.path.stem:
            continue
        prefix = f"{item.path.stem} [Fixed "
        for candidate in item.path.parent.iterdir():
            try:
                if (
                    is_ignorable_macos_metadata(candidate)
                    or not candidate.is_file()
                    or not candidate.name.startswith(prefix)
                    or not candidate.name.endswith("].m4b")
                ):
                    continue
                resolved = candidate.resolve(strict=True)
            except OSError:
                continue
            if resolved in seen:
                continue
            seen.add(resolved)
            if item.root is not None:
                try:
                    relative = resolved.relative_to(item.root)
                except ValueError:
                    relative = Path(resolved.name)
            else:
                relative = Path(resolved.name)
            expanded.append(InputItem(resolved, relative, item.root))

    expanded.sort(key=lambda entry: os.fsencode(str(entry.path)))
    return expanded


